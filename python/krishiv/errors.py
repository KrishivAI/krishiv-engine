def _render(error_class: str, parameters: dict[str, Any]) -> str:
    template = _TEMPLATES.get(error_class, error_class)
    text = re.sub(r"<(\w+)>", lambda m: str(parameters.get(m.group(1), m.group(0))), template)
    return f"[{error_class}] {text}"


# Classes (by prefix) with their own Spark exception type, before the SQLSTATE rules.
_BY_PREFIX: tuple[tuple[str, type[PySparkException]], ...] = (
    ("CAST_INVALID_INPUT", NumberFormatException),
    ("INCONSISTENT_BEHAVIOR_CROSS_VERSION", SparkUpgradeException),
    ("INVALID_ARRAY_INDEX", ArrayIndexOutOfBoundsException),
    ("INVALID_PARAMETER_VALUE", IllegalArgumentException),
    # Spark's legacy analysis errors (`_LEGACY_ERROR_TEMP_1xxx`) are `AnalysisException`s.
    ("_LEGACY_ERROR_TEMP_1", AnalysisException),
    ("PARSE_", ParseException),
    # Spark raises it from `QueryCompilationErrors` for every `action`/`type` pair.
    ("PYTHON_DATA_SOURCE_ERROR", AnalysisException),
    # `CANNOT_MODIFY_CONFIG` and `CANNOT_MODIFY_STATIC_CONFIG` (46110) come from `QueryCompilationErrors`.
    ("CANNOT_MODIFY_", AnalysisException),
    ("UNSUPPORTED_DATATYPE", ParseException),
    ("INVALID_SQL_SYNTAX", ParseException),
    # Spark's unnamed errors: 0xxx come from `QueryParsingErrors`, 1xxx from `QueryCompilationErrors`.
    ("_LEGACY_ERROR_TEMP_0", ParseException),
    ("_LEGACY_ERROR_TEMP_1", AnalysisException),
)
# By SQLSTATE: the analyzer's class 42 (42601, syntax, is the parser's), arithmetic
# (22012 division by zero, 22003 overflow), datetime (22007, 22008), 0A000 unsupported.
_BY_SQL_STATE: dict[str, type[PySparkException]] = {
    "42601": ParseException,
    "22012": ArithmeticException,
    "22003": ArithmeticException,
    "22007": DateTimeException,
    "22008": DateTimeException,
    "22023": IllegalArgumentException,
    "0A000": UnsupportedOperationException,
}


def _class_for(error_class: str, sql_state: str | None) -> type[PySparkException]:
    for prefix, cls in _BY_PREFIX:
        if error_class.startswith(prefix):
            return cls
    if sql_state in _BY_SQL_STATE:
        return _BY_SQL_STATE[sql_state]
    if sql_state is not None and sql_state.startswith("42"):
        return AnalysisException
    return SparkRuntimeException


def _from_native(
    error_class: str,
    sql_state: str | None,
    message: str,
    parameters: dict[str, str],
    contexts: list[tuple[Any, ...]] | None = None,
    rendered: str | None = None,
) -> PySparkException:
    """The exception for an engine error (called by ``krishiv._native``); ``rendered`` is
    the message followed by the SQL span that raised the error, when the query text is known."""
    return _class_for(error_class, sql_state)(
        message,
        errorClass=error_class,
        messageParameters=parameters,
        contexts=contexts,
        sqlState=sql_state,
        rendered=rendered,
    )


def not_expected_type(arg_name: str, expected: str, value: object) -> PySparkTypeError:
    return PySparkTypeError(
        errorClass="NOT_EXPECTED_TYPE",
        messageParameters={"arg_name": arg_name, "expected_type": expected, "arg_type": type(value).__name__},
    )


def not_implemented(feature: str) -> PySparkNotImplementedError:
    return PySparkNotImplementedError(errorClass="NOT_IMPLEMENTED", messageParameters={"feature": feature})


class UnsupportedFeatureAttributeError(UnsupportedOperationException, AttributeError):
    """``KRISHIV_UNSUPPORTED_FEATURE`` raised where Spark has an attribute Krishiv lacks. It is also an
    ``AttributeError``, so ``getattr(obj, name, default)``, ``hasattr`` and ``inspect.getmembers`` treat the
    name as absent, as they do for a plain missing attribute."""


class UnsupportedFeatureImportError(UnsupportedOperationException, ImportError):
    """``KRISHIV_UNSUPPORTED_FEATURE`` raised by importing a module Krishiv lacks. It is also an
    ``ImportError``, so ``try: import x except ImportError`` and ``pkgutil.walk_packages`` treat the
    module as absent."""


def _unsupported_args(feature: str) -> dict[str, Any]:
    return {
        "errorClass": "KRISHIV_UNSUPPORTED_FEATURE",
        "messageParameters": {"feature": feature},
        "sqlState": "0A000",
    }


def _unsupported_text(feature: str) -> str:
    return f"[KRISHIV_UNSUPPORTED_FEATURE] The feature {feature} is not supported by Krishiv yet. SQLSTATE: 0A000"


def unsupported_attribute(feature: str) -> UnsupportedFeatureAttributeError:
    """:func:`unsupported_feature` for an attribute or property (also an ``AttributeError``)."""
    return UnsupportedFeatureAttributeError(_unsupported_text(feature), **_unsupported_args(feature))


def unsupported_module(feature: str) -> UnsupportedFeatureImportError:
    """:func:`unsupported_feature` for a module (also an ``ImportError``)."""
    return UnsupportedFeatureImportError(_unsupported_text(feature), **_unsupported_args(feature))


def not_implemented_attribute(feature: str) -> PySparkNotImplementedAttributeError:
    """:func:`not_implemented` for a property: ``hasattr`` is ``False`` and the error still says ``NOT_IMPLEMENTED``."""
    return PySparkNotImplementedAttributeError(errorClass="NOT_IMPLEMENTED", messageParameters={"feature": feature})


def unsupported_feature(feature: str) -> UnsupportedOperationException:
    """The engine's unsupported-feature error, as the engine itself raises it
    (``KRISHIV_UNSUPPORTED_FEATURE``, SQLSTATE ``0A000``): for a PySpark method
    whose plan the engine cannot build or run yet, where emulating it is out
    of scope. Raised eagerly, as there is no plan to attach it to."""
    return UnsupportedOperationException(_unsupported_text(feature), **_unsupported_args(feature))
