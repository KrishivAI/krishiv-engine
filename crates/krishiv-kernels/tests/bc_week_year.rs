#[test]
fn a_bc_week_year_follows_the_jdk() {
    let pattern = LegacyPattern::new("YYYY ww").unwrap();
    for (date, week_year, week) in ORACLE {
        let (year, rest) = date.split_once('-').unwrap();
        let year: i64 = year.parse().unwrap();
        let (month, day) = rest.split_once('-').unwrap();
        let days = i32::try_from(days_from_civil(
            1 - year,
            month.parse().unwrap(),
            day.parse().unwrap(),
        ))
        .unwrap();
        assert_eq!(
            pattern.format_date(days).unwrap(),
            format!("{week_year} {week}"),
            "{date} BC"
        );
    }
}

/// Proleptic Gregorian days since 1970-01-01 (the label a date column holds).
fn days_from_civil(year: i64, month: i64, day: i64) -> i64 {
    let y = if month <= 2 { year - 1 } else { year };
    let era = y.div_euclid(400);
    let yoe = y - era * 400;
    let mp = (month + 9) % 12;
    let doy = (153 * mp + 2) / 5 + day - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}
