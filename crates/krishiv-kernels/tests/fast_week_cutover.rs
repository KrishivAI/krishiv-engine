#[test]
fn week_fields_around_the_cutover_match_spark() {
    let mut wrong = Vec::new();
    for &(text, pattern, want) in CASES {
        let got = DateTimePattern::new_fast(pattern).parse_date(text).unwrap();
        if got != want {
            wrong.push(format!(
                "{text:?} with {pattern:?}: {got:?}, Spark {want:?}"
            ));
        }
    }
    assert!(
        wrong.is_empty(),
        "{} of {} differ:\n{}",
        wrong.len(),
        CASES.len(),
        wrong.join("\n")
    );
}
