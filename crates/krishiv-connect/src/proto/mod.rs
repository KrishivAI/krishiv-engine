//! The Spark Connect protocol types, generated from the vendored `.proto`
//! files (`proto/spark-connect/<version>/` at the repository root) by
//! `tools/connect-protogen`.
//! There is one module per vendored Spark version.

/// Spark 4.2.0 (`package spark.connect`).
pub mod v4_2 {
    #[expect(
        missing_docs,
        reason = "generated by prost-build from the vendored protos; Spark's comments are not rustdoc"
    )]
    mod spark_connect {
        include!("v4_2/spark.connect.pb.rs");
    }
    pub use spark_connect::*;
}

/// The wire layout of every message, for the decoder's walk (`wire`).
/// Generated with the types of the version it names.
pub(crate) mod layout {
    include!("v4_2/layout.pb.rs");
}

/// A message of the package, as the decoder's walk sees it.
#[derive(Debug)]
pub(crate) struct Layout {
    /// The name within the package (`Read.DataSource`).
    pub(crate) name: &'static str,
    /// The size of the decoded Rust value.
    pub(crate) size: usize,
    /// What each field holds, sorted by field number.
    pub(crate) fields: &'static [(u32, Field)],
}

/// What a field holds, for the walk.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Field {
    /// A message of the package, by id: the walk descends into it.
    Message(u16),
    /// A string, bytes, or a message from outside the package
    /// (`google.protobuf.Any`, `Timestamp`), which prost decodes as a leaf.
    Bytes,
    /// A varint scalar (integer, bool or enum) that decodes to this many
    /// bytes.
    Varint(u8),
    /// A 32- or 64-bit fixed-width scalar: as many bytes decoded as on the
    /// wire.
    Fixed,
}

/// What a map entry costs decoded: a `BTreeMap` entry of a `String` key and
/// a value no bigger than a `String` (the value's own message, if it is
/// one, is counted separately), with room for the tree's nodes.
pub(crate) const MAP_ENTRY_SIZE: usize = 4 * size_of::<String>();
