//! Collects the per-entry codec tests: every `tests/features/<name>.rs` becomes `mod <name>;` of
//! the `features` test and every `tests/roundtrip/<name>.rs` one of the `roundtrip` test
//! (`$OUT_DIR/{feature,roundtrip}_tests.rs`, included there), so new tests are new files and no
//! shared list changes (`cargo xtask entry-dirs` checks the names). The library itself uses
//! nothing from here; a package without the directories gets empty lists. Dot files (editor
//! locks and swap files) are skipped.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn collect(dir: &Path, out_file: &Path) -> Result<(), Box<dyn std::error::Error>> {
    let mut names = Vec::new();
    if let Ok(entries) = std::fs::read_dir(dir) {
        for entry in entries {
            let path = entry?.path();
            if let Some(stem) = path
                .file_name()
                .and_then(|n| n.to_str())
                .filter(|n| !n.starts_with('.'))
                .and_then(|n| n.strip_suffix(".rs"))
            {
                names.push((stem.to_owned(), path));
            }
        }
    }
    names.sort();
    let mut out = format!(
        "// Generated by build.rs from {}; do not edit.\n",
        dir.display()
    );
    for (name, path) in &names {
        writeln!(
            out,
            "#[path = {:?}]\nmod {name};",
            path.display().to_string()
        )?;
    }
    std::fs::write(out_file, out)?;
    Ok(())
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo::rerun-if-changed=tests/features");
    println!("cargo::rerun-if-changed=tests/roundtrip");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let out = PathBuf::from(std::env::var("OUT_DIR")?);
    collect(
        &manifest.join("tests/features"),
        &out.join("feature_tests.rs"),
    )?;
    collect(
        &manifest.join("tests/roundtrip"),
        &out.join("roundtrip_tests.rs"),
    )?;
    Ok(())
}
