//! Collects the per-feature codec tests: every `tests/features/<name>.rs` becomes
//! `mod <name>;` of the `features` test (`$OUT_DIR/feature_tests.rs`, included there),
//! so a new feature's tests are a new file and no shared list changes
//! (`cargo xtask entry-dirs` checks the names). The library itself uses nothing
//! from here; a package without the directory gets an empty list.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("cargo::rerun-if-changed=tests/features");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let dir = manifest.join("tests/features");
    let mut names = Vec::new();
    if let Ok(entries) = std::fs::read_dir(&dir) {
        for entry in entries {
            let path = entry?.path();
            if let Some(stem) = path
                .file_name()
                .and_then(|n| n.to_str())
                .and_then(|n| n.strip_suffix(".rs"))
            {
                names.push((stem.to_owned(), path));
            }
        }
    }
    names.sort();
    let mut out = String::from("// Generated by build.rs from tests/features/; do not edit.\n");
    for (name, path) in &names {
        writeln!(
            out,
            "#[path = {:?}]\nmod {name};",
            path.display().to_string()
        )?;
    }
    std::fs::write(
        PathBuf::from(std::env::var("OUT_DIR")?).join("feature_tests.rs"),
        out,
    )?;
    Ok(())
}
