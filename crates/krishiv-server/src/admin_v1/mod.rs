/// The revision of this surface: an integer that grows whenever the descriptor snapshot changes
/// (design §6.3; `cargo xtask admin-api` requires the increase). `GetVersion` returns it and
/// `system.capabilities` carries it in the `("surface", "admin.v1", <revision>, ..)` row.
pub const ADMIN_V1_REVISION: i64 = 3;

/// Whether the surface is still `preview` (design D8): until the first release that ships it a
/// non-additive change is possible.
pub const PREVIEW: bool = true;

/// How long a mutating call is remembered by default.
pub const DEFAULT_IDEMPOTENCY_TTL: std::time::Duration = std::time::Duration::from_secs(3600);

/// The path every REST route sits under.
pub const REST_PREFIX: &str = "/api/admin/v1";

/// The gRPC service path, `/<package>.<service>/<method>`.
pub const GRPC_PREFIX: &str = "/krishiv.admin.v1.AdminService/";

/// What a route needs beyond an authenticated caller (the column of design §4's matrix).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum Privilege {
    /// Any authenticated caller.
    Authenticated,
}

/// One RPC's REST exposure, from `admin-v1/routes.json`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Route {
    /// The RPC's name in `AdminService`.
    pub rpc: String,
    /// `GET`, `POST`, `PUT`, `PATCH` or `DELETE`.
    pub method: String,
    /// The path under [`REST_PREFIX`]; a `:verb` suffix is an AIP-136 custom method.
    pub path: String,
    /// What the RPC checks.
    pub privilege: Privilege,
}

/// The route table: what the router is built from and what `xtask admin-api` documents.
#[must_use]
pub fn routes() -> &'static [Route] {
    static ROUTES: OnceLock<Vec<Route>> = OnceLock::new();
    ROUTES.get_or_init(|| {
        let text = include_str!("../../admin-v1/routes.json");
        let rows: Vec<serde_json::Value> = serde_json::from_str(text).unwrap_or_default();
        rows.iter()
            .filter_map(|row| {
                let field = |name: &str| row.get(name)?.as_str().map(str::to_owned);
                Some(Route {
                    rpc: field("rpc")?,
                    method: field("method")?,
                    path: field("path")?,
                    privilege: match field("privilege")?.as_str() {
                        "authenticated" => Privilege::Authenticated,
                        _ => return None,
                    },
                })
            })
            .collect()
    })
}

/// The descriptor set of `krishiv.admin.v1`, the one source of the REST JSON.
///
/// # Panics
///
/// Never in a build whose `descriptor.bin` is the generator's output (a test decodes it).
#[must_use]
pub fn descriptor_pool() -> &'static DescriptorPool {
    static POOL: OnceLock<Option<DescriptorPool>> = OnceLock::new();
    POOL.get_or_init(|| DescriptorPool::decode(include_bytes!("descriptor.bin").as_slice()).ok())
        .as_ref()
        .unwrap_or_else(|| {
            static EMPTY: OnceLock<DescriptorPool> = OnceLock::new();
            EMPTY.get_or_init(DescriptorPool::new)
        })
}

/// The class of an admin error, which decides the gRPC status and the HTTP status (design §6.4).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum ErrorKind {
    /// A bad request: `INVALID_ARGUMENT` / 400.
    InvalidArgument,
    /// No or bad credentials: `UNAUTHENTICATED` / 401.
    Unauthenticated,
    /// An access refusal: `PERMISSION_DENIED` / 403.
    PermissionDenied,
    /// An unknown id, or one the caller may not act on: `NOT_FOUND` / 404.
    NotFound,
    /// A failed precondition (stale etag, read-only file): `FAILED_PRECONDITION` / 412.
    FailedPrecondition,
    /// A reused idempotency key: `ALREADY_EXISTS` / 409.
    AlreadyExists,
    /// A request over the size cap: `RESOURCE_EXHAUSTED` / 413.
    ResourceExhausted,
    /// The service cannot answer now: `UNAVAILABLE` / 503.
    Unavailable,
    /// A bug: `INTERNAL` / 500.
    Internal,
}

/// An admin error: always an error class (the permanent code), its SQLSTATE and message
/// parameters, never only text (design §6.4).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AdminError {
    /// Which status it maps to.
    pub kind: ErrorKind,
    /// The error class with its sub-class, `INVALID_HANDLE.SESSION_NOT_FOUND`.
    pub error_class: String,
    /// The SQLSTATE of the class.
    pub sql_state: String,
    /// The message parameters, in key order.
    pub parameters: BTreeMap<String, String>,
    /// The message, for people; clients branch on the class.
    pub message: String,
    /// A refusal disguised as another error (a not-found for an id the caller may not act on):
    /// its action record says `denied`, also when a stored response is replayed.
    pub denied: bool,
}

impl AdminError {
    /// An error of `kind` with its class, SQLSTATE and message.
    #[must_use]
    pub fn new(
        kind: ErrorKind,
        error_class: &str,
        sql_state: &str,
        message: impl Into<String>,
    ) -> Self {
        Self {
            kind,
            error_class: error_class.to_owned(),
            sql_state: sql_state.to_owned(),
            parameters: BTreeMap::new(),
            message: message.into(),
            denied: false,
        }
    }

    /// The error marked as a refusal disguised as another error.
    #[must_use]
    pub fn disguised_denial(mut self) -> Self {
        self.denied = true;
        self
    }

    /// The error with message parameter `name`.
    #[must_use]
    pub fn with_parameter(mut self, name: &str, value: impl Into<String>) -> Self {
        self.parameters.insert(name.to_owned(), value.into());
        self
    }

    /// A bug: `INTERNAL_ERROR`, SQLSTATE XX000.
    #[must_use]
    pub fn internal(message: impl Into<String>) -> Self {
        Self::new(ErrorKind::Internal, "INTERNAL_ERROR", "XX000", message)
    }

    /// `KRISHIV_ADMIN_INVALID_REQUEST`: a bad request (a REST body with an unknown field, an
    /// unparsable body, a wrong `Content-Type` or `Host`).
    #[must_use]
    pub fn invalid_argument(message: impl Into<String>) -> Self {
        let message = message.into();
        Self::new(
            ErrorKind::InvalidArgument,
            "KRISHIV_ADMIN_INVALID_REQUEST",
            "22023",
            format!("The admin API request is not valid: {message}."),
        )
        .with_parameter("reason", message)
    }

    /// The top-level condition of the class, `INVALID_HANDLE` for `INVALID_HANDLE.SESSION_NOT_FOUND`
    /// (the gRPC `ErrorInfo.reason`).
    #[must_use]
    pub fn reason(&self) -> &str {
        self.error_class
            .split('.')
            .next()
            .unwrap_or(&self.error_class)
    }
}

/// The result of an admin call.
pub type AdminResult<T> = Result<T, AdminError>;

/// One call as the API sees it: who made it, over which transport, and its request id (the
/// idempotency key the caller sent, or one generated for the call).
#[derive(Debug, Clone)]
pub struct Call {
    /// The authenticated caller.
    pub caller: Caller,
    /// `grpc` or `rest`.
    pub transport: &'static str,
    /// The request id.
    pub request_id: String,
}

/// What `AdminService` does: one method per RPC, the same for gRPC and REST. The caller has been
/// authenticated before a method runs (the guard of [`router`]); what the caller may do with
/// another principal's work is for the method to decide, and every mutating method writes its own
/// record with [`action::record`].
pub trait AdminApi: Send + Sync + 'static {
    /// What the idempotency store keys a caller's request ids on: the caller's full identity,
    /// not its name (two principals with one name must share nothing). The default is the name.
    fn idempotency_scope(&self, call: &Call) -> String {
        call.caller.principal.clone()
    }

    /// The engine version and the surface revision.
    fn get_version(&self, call: &Call) -> BoxFuture<'_, AdminResult<GetVersionResponse>>;

    /// The `system.capabilities` rows.
    fn get_capabilities(&self, call: &Call) -> BoxFuture<'_, AdminResult<GetCapabilitiesResponse>>;

    /// The caller's sessions, or all of them with `Monitor`.
    fn list_sessions(
        &self,
        call: &Call,
        request: ListSessionsRequest,
    ) -> BoxFuture<'_, AdminResult<ListSessionsResponse>>;

    /// Ends a session: the caller's own, or any with `Operate`.
    fn kill_session(
        &self,
        call: &Call,
        request: KillSessionRequest,
    ) -> BoxFuture<'_, AdminResult<KillSessionResponse>>;

    /// The caller's queries, or all of them with `Monitor`.
    fn list_queries(
        &self,
        call: &Call,
        request: ListQueriesRequest,
    ) -> BoxFuture<'_, AdminResult<ListQueriesResponse>>;

    /// Cancels a query: the caller's own, or any with `Operate`.
    fn cancel_query(
        &self,
        call: &Call,
        request: CancelQueryRequest,
    ) -> BoxFuture<'_, AdminResult<CancelQueryResponse>>;

    /// Cancels the queries a tag selector matches: the caller's own, or all with `Operate`.
    fn cancel_queries_by_tag(
        &self,
        call: &Call,
        request: CancelQueriesByTagRequest,
    ) -> BoxFuture<'_, AdminResult<CancelQueriesByTagResponse>>;

    /// Per-check readiness (`Monitor`).
    fn get_readiness(&self, _call: &Call) -> BoxFuture<'_, AdminResult<GetReadinessResponse>> {
        unsupported("GetReadiness")
    }

    /// The drain state (`Monitor`).
    fn get_drain_status(&self, _call: &Call) -> BoxFuture<'_, AdminResult<GetDrainStatusResponse>> {
        unsupported("GetDrainStatus")
    }

    /// Starts or shortens a drain (`Manage` on the cluster).
    fn drain(
        &self,
        _call: &Call,
        _request: DrainRequest,
    ) -> BoxFuture<'_, AdminResult<DrainResponse>> {
        unsupported("Drain")
    }

    /// Back to serving (`Manage` on the cluster).
    fn resume_serving(
        &self,
        _call: &Call,
        _request: ResumeServingRequest,
    ) -> BoxFuture<'_, AdminResult<ResumeServingResponse>> {
        unsupported("ResumeServing")
    }
}

/// The answer of an [`AdminApi`] that does not implement an RPC.
fn unsupported<T: Send + 'static>(rpc: &str) -> BoxFuture<'static, AdminResult<T>> {
    let error = AdminError::new(
        ErrorKind::FailedPrecondition,
        "KRISHIV_UNSUPPORTED_FEATURE",
        "0A000",
        format!("{rpc} is not available on this server."),
    );
    Box::pin(std::future::ready(Err(error)))
}

/// How the admin listener is reached, for the browser rules of design §3.
#[derive(Debug, Clone)]
pub struct AdminConfig {
    /// The listener is bound to a loopback address: a `Host` outside `localhost`, `127.0.0.1`,
    /// `[::1]` and [`AdminConfig::allowed_hosts`] is refused with 421 (DNS rebinding).
    pub loopback: bool,
    /// Extra host names accepted on a loopback listener (`krishiv.server.allowedHosts`).
    pub allowed_hosts: Vec<String>,
    /// How long a mutating call's response is remembered for its request id (design §6.2:
    /// `krishiv.server.admin.idempotencyTtl`, 1 h).
    pub idempotency_ttl: std::time::Duration,
}

impl Default for AdminConfig {
    fn default() -> Self {
        Self {
            loopback: false,
            allowed_hosts: Vec::new(),
            idempotency_ttl: DEFAULT_IDEMPOTENCY_TTL,
        }
    }
}

impl AdminConfig {
    /// A configuration for a listener bound to `addr`.
    #[must_use]
    pub fn for_listener(addr: IpAddr, allowed_hosts: Vec<String>) -> Self {
        Self {
            loopback: addr.to_canonical().is_loopback(),
            allowed_hosts,
            idempotency_ttl: DEFAULT_IDEMPOTENCY_TTL,
        }
    }
}

/// Puts `GET /api/v1/version` (the deprecated alias of `GetVersion`) behind `guard` as
/// [`Access::Authenticated`](crate::guard::Access::Authenticated), as `GetVersion` is: with
/// authentication configured an unauthenticated version string is not kept (design D6, ADR 0046
/// §3c). Apply it to the whole admin app; every other path passes through untouched.
pub fn guard_version_alias(app: Router, guard: Arc<dyn Guard>) -> Router {
    app.layer(axum::middleware::from_fn_with_state(
        guard,
        rest::guard_version_alias,
    ))
}

/// The admin routes, REST and gRPC, behind `guard` and the browser rules: merge it into the admin
/// listener's router.
pub fn router(api: Arc<dyn AdminApi>, guard: Arc<dyn Guard>, config: AdminConfig) -> Router {
    let core = Arc::new(core::Core::new(api, config.idempotency_ttl));
    let rest = rest::router(Arc::clone(&core), Arc::clone(&guard));
    let grpc = grpc::router(core, guard);
    rest.merge(grpc).layer(axum::middleware::from_fn_with_state(
        Arc::new(config),
        browser::enforce,
    ))
}
