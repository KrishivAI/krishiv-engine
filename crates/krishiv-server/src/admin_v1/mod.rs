/// The revision of this surface: an integer that grows whenever the descriptor snapshot changes
/// (design §6.3; `cargo xtask admin-api` requires the increase). `GetVersion` returns it and
/// `system.capabilities` carries it in the `("surface", "admin.v1", <revision>, ..)` row.
pub const ADMIN_V1_REVISION: i64 = 1;

/// Whether the surface is still `preview` (design D8): until the first release that ships it a
/// non-additive change is possible.
pub const PREVIEW: bool = true;

/// The path every REST route sits under.
pub const REST_PREFIX: &str = "/api/admin/v1";

/// The gRPC service path, `/<package>.<service>/<method>`.
pub const GRPC_PREFIX: &str = "/krishiv.admin.v1.AdminService/";

/// What a route needs beyond an authenticated caller (the column of design §4's matrix).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum Privilege {
    /// Any authenticated caller.
    Authenticated,
}

/// One RPC's REST exposure, from `admin-v1/routes.json`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Route {
    /// The RPC's name in `AdminService`.
    pub rpc: String,
    /// `GET`, `POST`, `PUT`, `PATCH` or `DELETE`.
    pub method: String,
    /// The path under [`REST_PREFIX`]; a `:verb` suffix is an AIP-136 custom method.
    pub path: String,
    /// What the RPC checks.
    pub privilege: Privilege,
}

/// The route table: what the router is built from and what `xtask admin-api` documents.
#[must_use]
pub fn routes() -> &'static [Route] {
    static ROUTES: OnceLock<Vec<Route>> = OnceLock::new();
    ROUTES.get_or_init(|| {
        let text = include_str!("../../admin-v1/routes.json");
        let rows: Vec<serde_json::Value> = serde_json::from_str(text).unwrap_or_default();
        rows.iter()
            .filter_map(|row| {
                let field = |name: &str| row.get(name)?.as_str().map(str::to_owned);
                Some(Route {
                    rpc: field("rpc")?,
                    method: field("method")?,
                    path: field("path")?,
                    privilege: match field("privilege")?.as_str() {
                        "authenticated" => Privilege::Authenticated,
                        _ => return None,
                    },
                })
            })
            .collect()
    })
}

/// The descriptor set of `krishiv.admin.v1`, the one source of the REST JSON.
///
/// # Panics
///
/// Never in a build whose `descriptor.bin` is the generator's output (a test decodes it).
#[must_use]
pub fn descriptor_pool() -> &'static DescriptorPool {
    static POOL: OnceLock<Option<DescriptorPool>> = OnceLock::new();
    POOL.get_or_init(|| DescriptorPool::decode(include_bytes!("descriptor.bin").as_slice()).ok())
        .as_ref()
        .unwrap_or_else(|| {
            static EMPTY: OnceLock<DescriptorPool> = OnceLock::new();
            EMPTY.get_or_init(DescriptorPool::new)
        })
}

/// The class of an admin error, which decides the gRPC status and the HTTP status (design §6.4).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub enum ErrorKind {
    /// A bad request: `INVALID_ARGUMENT` / 400.
    InvalidArgument,
    /// No or bad credentials: `UNAUTHENTICATED` / 401.
    Unauthenticated,
    /// An access refusal: `PERMISSION_DENIED` / 403.
    PermissionDenied,
    /// An unknown id, or one the caller may not act on: `NOT_FOUND` / 404.
    NotFound,
    /// A failed precondition (stale etag, read-only file): `FAILED_PRECONDITION` / 412.
    FailedPrecondition,
    /// A reused idempotency key: `ALREADY_EXISTS` / 409.
    AlreadyExists,
    /// A request over the size cap: `RESOURCE_EXHAUSTED` / 413.
    ResourceExhausted,
    /// The service cannot answer now: `UNAVAILABLE` / 503.
    Unavailable,
    /// A bug: `INTERNAL` / 500.
    Internal,
}

/// An admin error: always an error class (the permanent code), its SQLSTATE and message
/// parameters, never only text (design §6.4).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AdminError {
    /// Which status it maps to.
    pub kind: ErrorKind,
    /// The error class with its sub-class, `INVALID_HANDLE.SESSION_NOT_FOUND`.
    pub error_class: String,
    /// The SQLSTATE of the class.
    pub sql_state: String,
    /// The message parameters, in key order.
    pub parameters: BTreeMap<String, String>,
    /// The message, for people; clients branch on the class.
    pub message: String,
}

impl AdminError {
    /// An error of `kind` with its class, SQLSTATE and message.
    #[must_use]
    pub fn new(
        kind: ErrorKind,
        error_class: &str,
        sql_state: &str,
        message: impl Into<String>,
    ) -> Self {
        Self {
            kind,
            error_class: error_class.to_owned(),
            sql_state: sql_state.to_owned(),
            parameters: BTreeMap::new(),
            message: message.into(),
        }
    }

    /// The error with message parameter `name`.
    #[must_use]
    pub fn with_parameter(mut self, name: &str, value: impl Into<String>) -> Self {
        self.parameters.insert(name.to_owned(), value.into());
        self
    }

    /// A bug: `INTERNAL_ERROR`, SQLSTATE XX000.
    #[must_use]
    pub fn internal(message: impl Into<String>) -> Self {
        Self::new(ErrorKind::Internal, "INTERNAL_ERROR", "XX000", message)
    }

    /// `INVALID_PARAMETER_VALUE`-class refusal of a request (a REST body with an unknown field, an
    /// unparsable body).
    #[must_use]
    pub fn invalid_argument(message: impl Into<String>) -> Self {
        Self::new(
            ErrorKind::InvalidArgument,
            "INVALID_PARAMETER_VALUE",
            "22023",
            message,
        )
    }

    /// The top-level condition of the class, `INVALID_HANDLE` for `INVALID_HANDLE.SESSION_NOT_FOUND`
    /// (the gRPC `ErrorInfo.reason`).
    #[must_use]
    pub fn reason(&self) -> &str {
        self.error_class
            .split('.')
            .next()
            .unwrap_or(&self.error_class)
    }
}

/// The result of an admin call.
pub type AdminResult<T> = Result<T, AdminError>;

/// What `AdminService` does: one method per RPC, the same for gRPC and REST. The caller has been
/// authenticated and authorized for the RPC before a method runs (the guard of [`router`]).
pub trait AdminApi: Send + Sync + 'static {
    /// The engine version and the surface revision.
    fn get_version(&self) -> BoxFuture<'_, AdminResult<GetVersionResponse>>;

    /// The `system.capabilities` rows.
    fn get_capabilities(&self) -> BoxFuture<'_, AdminResult<GetCapabilitiesResponse>>;
}

/// How the admin listener is reached, for the browser rules of design §3.
#[derive(Debug, Clone, Default)]
pub struct AdminConfig {
    /// The listener is bound to a loopback address: a `Host` outside `localhost`, `127.0.0.1`,
    /// `[::1]` and [`AdminConfig::allowed_hosts`] is refused with 421 (DNS rebinding).
    pub loopback: bool,
    /// Extra host names accepted on a loopback listener (`krishiv.server.allowedHosts`).
    pub allowed_hosts: Vec<String>,
}

impl AdminConfig {
    /// A configuration for a listener bound to `addr`.
    #[must_use]
    pub fn for_listener(addr: IpAddr, allowed_hosts: Vec<String>) -> Self {
        Self {
            loopback: addr.is_loopback(),
            allowed_hosts,
        }
    }
}

/// The admin routes, REST and gRPC, behind `guard` and the browser rules: merge it into the admin
/// listener's router.
pub fn router(api: Arc<dyn AdminApi>, guard: Arc<dyn Guard>, config: AdminConfig) -> Router {
    let rest = rest::router(Arc::clone(&api), Arc::clone(&guard));
    let grpc = grpc::router(api, guard);
    rest.merge(grpc).layer(axum::middleware::from_fn_with_state(
        Arc::new(config),
        browser::enforce,
    ))
}
