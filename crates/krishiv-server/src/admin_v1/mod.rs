//! `krishiv.admin.v1`, the control API (design P3-T066, ADR 0036, ADR 0046): one service on two
//! transports. gRPC (`/krishiv.admin.v1.AdminService/*`) and REST (`/api/admin/v1/*`) both end in
//! one [`AdminApi`], so they answer the same; REST bodies are the proto3 JSON mapping of the same
//! messages, produced and parsed through the descriptor ([`descriptor_pool`]), never through
//! hand-written mirror types.
//!
//! - `pb`: the generated messages and the tonic server side (`tools/admin-protogen`; never edited);
//! - [`routes`]: the REST verb, path and privilege of each RPC (`admin-v1/routes.json`);
//! - `rest`: the axum routes, the JSON mapping and the error envelope;
//! - `grpc`: the tonic service and its status mapping;
//! - `browser`: the rules for requests that come from a browser (design §3).

