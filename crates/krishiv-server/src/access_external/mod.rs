impl ExternalAccess {
    /// The provider over `config`'s endpoint. The channel connects on first use (a service
    /// that is down at startup is a denial per call, not a startup failure).
    ///
    /// # Errors
    /// `KRISHIV_INVALID_CONFIG_VALUE` when the token is not valid header text or TLS cannot be
    /// set up for the endpoint.
    pub fn new(config: &ExternalConfig) -> Result<Arc<Self>, krishiv_common::error::KrishivError> {
        let channel = config.endpoint.channel()?;
        Ok(Self::over(
            AccessPolicyClient::new(channel),
            config.timeout,
            config.bearer()?,
            config.system,
        ))
    }

    /// The provider over an existing channel (tests, an in-process adapter).
    #[must_use]
    pub fn over(
        client: AccessPolicyClient<Channel>,
        timeout: Duration,
        token: Option<tonic::metadata::MetadataValue<tonic::metadata::Ascii>>,
        system: bool,
    ) -> Arc<Self> {
        Arc::new(Self {
            client,
            timeout,
            token,
            system,
            noted: Mutex::new(Noted::default()),
            call_seq: AtomicU64::new(0),
            untrusted: AtomicU64::new(0),
            version_asked: Mutex::new(None),
            version_in_flight: AtomicBool::new(false),
            version_done: tokio::sync::Notify::new(),
            denials: AtomicU64::new(0),
            calls: AtomicU64::new(0),
        })
    }

    /// One session's policy over this provider.
    #[must_use]
    pub fn policy(self: &Arc<Self>) -> ExternalPolicy {
        ExternalPolicy {
            access: Arc::clone(self),
            memo: Mutex::new(HashMap::new()),
            stage: AtomicU64::new(0),
            answered: Mutex::new(Answered::default()),
        }
    }

    /// How many refusals of this provider analyses reported ([`AccessPolicy::denied`]).
    #[must_use]
    pub fn denials(&self) -> u64 {
        self.denials.load(Ordering::Relaxed)
    }

    /// How many `Check` calls were made.
    #[must_use]
    pub fn calls(&self) -> u64 {
        self.calls.load(Ordering::Relaxed)
    }

    /// Whether the provider decides `securable`: every data securable, and `System(..)` only
    /// when `krishiv.access.external.securables` lists `system`.
    #[must_use]
    pub fn decides(&self, securable: &Securable) -> bool {
        !matches!(securable, Securable::System(_)) || self.system
    }

    fn request<T>(&self, message: T) -> tonic::Request<T> {
        let mut request = tonic::Request::new(message);
        request.set_timeout(self.timeout);
        if let Some(token) = &self.token {
            request
                .metadata_mut()
                .insert("authorization", token.clone());
        }
        request
    }

    /// Decides `items` for `principal`, in calls of at most [`MAX_ITEMS_PER_CHECK`]; `true` is
    /// an allow. Any failure denies every item of its call. Also returns the version the last
    /// call that answered reported, and whether every call that answered reported one policy
    /// version: when the version moved between the calls, some answers are from a policy the
    /// others replaced.
    async fn decide_versioned(
        &self,
        principal: &Principal,
        items: &[(Securable, Privilege)],
    ) -> (Vec<bool>, Option<u64>, bool) {
        let mut out = Vec::with_capacity(items.len());
        let mut version: Option<u64> = None;
        let mut one_version = true;
        let who = convert::principal(principal);
        for chunk in items.chunks(MAX_ITEMS_PER_CHECK) {
            let message = pb::CheckRequest {
                principal: Some(who.clone()),
                items: chunk
                    .iter()
                    .map(|(s, p)| pb::Item {
                        securable: Some(convert::securable(s)),
                        privilege: convert::privilege(*p).into(),
                    })
                    .collect(),
                statement_class: String::new(),
                query_id: String::new(),
            };
            self.calls.fetch_add(1, Ordering::Relaxed);
            let seq = self.begin_call();
            let mut client = self.client.clone();
            let call = client.check(self.request(message));
            let answer = match tokio::time::timeout(self.timeout, call).await {
                Ok(Ok(response)) => Some(response.into_inner()),
                Ok(Err(status)) => {
                    tracing::warn!(
                        target: "krishiv::access",
                        provider = "external",
                        code = ?status.code(),
                        "the policy service refused the check; denying"
                    );
                    None
                }
                Err(_) => {
                    tracing::warn!(
                        target: "krishiv::access",
                        provider = "external",
                        timeout_ms = u64::try_from(self.timeout.as_millis()).unwrap_or(u64::MAX),
                        "the policy service did not answer in time; denying"
                    );
                    None
                }
            };
            if let Some(v) = answer
                .as_ref()
                .filter(|a| a.decisions.len() == chunk.len())
                .map(|a| a.policy_version)
            {
                one_version &= version.is_none_or(|seen| seen == v);
                version = Some(v);
            }
            out.extend(self.read_answer(seq, answer, chunk.len()));
        }
        (out, version, one_version)
    }

    /// The decisions of one response for `n` items: all denials unless it holds exactly `n`
    /// decisions; each `true` only for `DECISION_ALLOW`.
    fn read_answer(&self, seq: u64, answer: Option<pb::CheckResponse>, n: usize) -> Vec<bool> {
        let Some(answer) = answer else {
            self.note(seq, None);
            return vec![false; n];
        };
        if answer.decisions.len() != n {
            // A malformed answer is a failed call: the version it names is not trusted.
            self.note(seq, None);
            tracing::warn!(
                target: "krishiv::access",
                provider = "external",
                items = n,
                decisions = answer.decisions.len(),
                "the policy service answered the wrong number of decisions; denying"
            );
            return vec![false; n];
        }
        self.note(seq, Some(answer.policy_version));
        answer
            .decisions
            .iter()
            .map(|d| *d == i32::from(pb::Decision::Allow))
            .collect()
    }

    /// The number of a call about to start.
    fn begin_call(&self) -> u64 {
        self.call_seq.fetch_add(1, Ordering::Relaxed) + 1
    }

    /// Records what call `seq` learned: `Some(v)` the version it reported, `None` a failure. Only
    /// a call started after the one last recorded counts, so a slow answer never brings back an
    /// older version. Any change counts, downwards too (a restarted service, hash-style
    /// versions): the cache compares versions for equality only (review D3). 0 (unknown) and a
    /// failure leave the version untrusted, and so does one with the top bit set.
    fn note(&self, seq: u64, reported: Option<u64>) {
        let mut noted = self
            .noted
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        if seq < noted.seq {
            return;
        }
        noted.seq = seq;
        noted.at = Some(Instant::now());
        match reported {
            // A version with the top bit set could equal an untrusted value: not trusted (review r2).
            Some(v) if v != 0 && v < 1 << 63 => {
                noted.version = v;
                noted.failed = false;
            }
            _ => noted.failed = true,
        }
    }

    /// Records `v` as reported by a call starting now (tests).
    #[cfg(test)]
    fn note_version(&self, v: u64) {
        let seq = self.begin_call();
        self.note(seq, Some(v));
    }

    /// The policy version for a context fingerprint. A trusted version is the service's, reported
    /// within the last [`VERSION_STALE`]; while there is none (nothing reported yet, a reported 0,
    /// the last call failed, or the last report is older: the first statement after an idle
    /// spell, review D4) every call gives a value never given before, with the top bit set so it
    /// cannot equal a service version, so no analysis made under it is reused (ADR 0036: fail
    /// closed; review M2).
    fn current_version(&self) -> PolicyVersion {
        let trusted = {
            let noted = self
                .noted
                .lock()
                .unwrap_or_else(std::sync::PoisonError::into_inner);
            let fresh = noted.at.is_some_and(|t| t.elapsed() < VERSION_STALE);
            (fresh && !noted.failed && noted.version != 0).then_some(noted.version)
        };
        match trusted {
            Some(v) => PolicyVersion(v),
            None => self.untrusted_version(),
        }
    }

    /// A version never given before, with the top bit set so it cannot equal a service version.
    fn untrusted_version(&self) -> PolicyVersion {
        let n = self.untrusted.fetch_add(1, Ordering::Relaxed);
        PolicyVersion((1 << 63) | n)
    }

    /// Asks the service for its version in the background, at most once per
    /// [`VERSION_INTERVAL`], when a Tokio runtime is current.
    fn refresh_version(self: &Arc<Self>) {
        {
            let mut asked = self
                .version_asked
                .lock()
                .unwrap_or_else(std::sync::PoisonError::into_inner);
            if asked.is_some_and(|t| t.elapsed() < VERSION_INTERVAL) {
                return;
            }
            *asked = Some(Instant::now());
        }
        let Ok(handle) = tokio::runtime::Handle::try_current() else {
            return;
        };
        if self.version_in_flight.swap(true, Ordering::AcqRel) {
            return;
        }
        /// Clears the in-flight flag however the task ends (finished, dropped with its runtime).
        struct InFlight(Arc<ExternalAccess>);
        impl Drop for InFlight {
            fn drop(&mut self) {
                self.0.version_in_flight.store(false, Ordering::Release);
            }
        }
        let guard = InFlight(Arc::clone(self));
        handle.spawn(async move {
            let this = &guard.0;
            let seq = this.begin_call();
            let mut client = this.client.clone();
            let call = client.version(this.request(pb::VersionRequest {}));
            match tokio::time::timeout(this.timeout, call).await {
                Ok(Ok(response)) => this.note(seq, Some(response.into_inner().policy_version)),
                _ => this.note(seq, None),
            }
            this.version_done.notify_waiters();
        });
    }
}

/// A prefetched pair: the principal and the securable as sent (the wire form is exactly what
/// the service decided on, `delegated_by` and `definer_for` included; `Securable` is not
/// `Hash`) and the privilege.
type MemoKey = (Vec<u8>, Vec<u8>, Privilege);

fn memo_key(principal: &[u8], securable: &Securable, privilege: Privilege) -> MemoKey {
    (
        principal.to_vec(),
        prost::Message::encode_to_vec(&convert::securable(securable)),
        privilege,
    )
}

fn principal_key(principal: &Principal) -> Vec<u8> {
    prost::Message::encode_to_vec(&convert::principal(principal))
}

/// One session's `external` policy (see the module docs).
pub struct ExternalPolicy {
    access: Arc<ExternalAccess>,
    /// Prefetched decisions, each answering one `check` within [`PREFETCH_LIFETIME`].
    memo: Mutex<HashMap<MemoKey, (bool, Instant)>>,
    /// The latest prefetch's number, read and written under the `memo` lock: a prefetch stores
    /// its answers only if no later one started while it waited for the service.
    stage: AtomicU64,
    /// The policy versions this stage's answers came from. Lock order: `memo`, then this.
    answered: Mutex<Answered>,
}

/// The policy versions of one stage's answers, reset by each prefetch.
#[derive(Debug, Default)]
struct Answered {
    /// The version the stage's first kept answer reported.
    version: Option<u64>,
    /// Whether a later answer reported another version.
    mixed: bool,
}

impl std::fmt::Debug for ExternalPolicy {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ExternalPolicy")
            .field("access", &self.access)
            .finish_non_exhaustive()
    }
}

impl ExternalPolicy {
    /// The server-wide provider.
    #[must_use]
    pub fn access(&self) -> &Arc<ExternalAccess> {
        &self.access
    }

    fn memo(&self) -> std::sync::MutexGuard<'_, HashMap<MemoKey, (bool, Instant)>> {
        self.memo
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }

    fn answered(&self) -> std::sync::MutexGuard<'_, Answered> {
        self.answered
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }

    /// Records the version a `check` answer reported. When it differs from the stage's earlier
    /// answers, the policy changed while the stage was analysed: the prefetched answers left (of
    /// the replaced version) are dropped, so each later `check` asks the service, and the stage
    /// is marked mixed until the next prefetch.
    fn observe(&self, v: u64) {
        let changed = {
            let mut answered = self.answered();
            match answered.version {
                None => {
                    answered.version = Some(v);
                    false
                }
                Some(seen) if seen != v => {
                    answered.version = Some(v);
                    answered.mixed = true;
                    true
                }
                Some(_) => false,
            }
        };
        if changed {
            self.memo().clear();
            tracing::warn!(
                target: "krishiv::access",
                provider = "external",
                "the policy version changed during an analysis; its prefetched answers are dropped"
            );
        }
    }

    /// The prefetched decision for a pair, taken (it answers once), if still fresh.
    fn take(&self, key: &MemoKey) -> Option<bool> {
        let (allow, at) = self.memo().remove(key)?;
        (at.elapsed() < PREFETCH_LIFETIME).then_some(allow)
    }
}

fn decision(allow: bool) -> AccessDecision {
    if allow {
        AccessDecision::Allow
    } else {
        AccessDecision::Deny {
            reason: "the external policy service did not allow it".to_owned(),
        }
    }
}

impl AccessPolicy for ExternalPolicy {
    fn version(&self) -> PolicyVersion {
        self.access.refresh_version();
        // An analysis that took allows from two policy versions is fingerprinted with neither
        // (review: one version per analysis), so it is never reused.
        if self.answered().mixed {
            return self.access.untrusted_version();
        }
        self.access.current_version()
    }

    fn check<'a>(
        &'a self,
        principal: &'a Principal,
        securable: &'a Securable,
        privilege: Privilege,
    ) -> BoxFuture<'a, Result<AccessDecision, krishiv_common::error::KrishivError>> {
        Box::pin(async move {
            if !self.access.decides(securable)
                || !convert::known(securable, privilege)
                || !convert::known_principal(principal)
            {
                return Ok(decision(false));
            }
            let key = memo_key(&principal_key(principal), securable, privilege);
            if let Some(allow) = self.take(&key) {
                return Ok(decision(allow));
            }
            let item = [(securable.clone(), privilege)];
            let (answers, version, _) = self.access.decide_versioned(principal, &item).await;
            if let Some(v) = version {
                self.observe(v);
            }
            Ok(decision(answers.first().copied().unwrap_or(false)))
        })
    }

    fn denied(&self, _principal: &Principal, _securable: &Securable, _privilege: Privilege) {
        self.access.denials.fetch_add(1, Ordering::Relaxed);
    }

    fn prefetch<'a>(
        &'a self,
        principal: &'a Principal,
        items: &'a [(Securable, Privilege)],
    ) -> BoxFuture<'a, ()> {
        Box::pin(async move {
            // Each prefetch replaces what an earlier stage left: an answer never outlives the stage
            // that fetched it (review m2), and a prefetch that a later one overtook while it
            // waited for the service stores nothing.
            let stage = {
                let mut memo = self.memo();
                memo.clear();
                *self.answered() = Answered::default();
                self.stage.fetch_add(1, Ordering::Relaxed) + 1
            };
            if !convert::known_principal(principal) {
                return;
            }
            let asked: Vec<(Securable, Privilege)> = items
                .iter()
                .filter(|(s, p)| self.access.decides(s) && convert::known(s, *p))
                .cloned()
                .collect();
            if asked.is_empty() {
                return;
            }
            let (answers, version, one_version) =
                self.access.decide_versioned(principal, &asked).await;
            let id = principal_key(principal);
            let now = Instant::now();
            let mut memo = self.memo();
            if self.stage.load(Ordering::Relaxed) != stage {
                return;
            }
            memo.clear();
            // Answers from two policy versions (the policy changed between the calls of a large
            // stage) are not kept: each `check` then asks the service itself, so no allow of a
            // replaced version authorizes an analysis fingerprinted with the new one.
            if !one_version {
                tracing::warn!(
                    target: "krishiv::access",
                    provider = "external",
                    "the policy version changed during a prefetch; its answers are not kept"
                );
                return;
            }
            // A `check` that finished while this prefetch waited for the service has already
            // recorded the version it saw (review 8976a61d1): merge with it, never overwrite. If
            // they differ, the stage took answers from two versions: it is mixed and the
            // prefetched answers are not kept, as when a later `check` sees another version.
            {
                let mut answered = self.answered();
                match (answered.version, version) {
                    (Some(seen), Some(v)) if seen != v => {
                        answered.mixed = true;
                        drop(answered);
                        tracing::warn!(
                            target: "krishiv::access",
                            provider = "external",
                            "the policy version changed during a prefetch; its answers are not kept"
                        );
                        return;
                    }
                    (None, Some(v)) => answered.version = Some(v),
                    _ => {}
                }
            }
            for ((securable, privilege), allow) in asked.into_iter().zip(answers).take(MEMO_LIMIT) {
                memo.insert(memo_key(&id, &securable, privilege), (allow, now));
            }
        })
    }

    fn decides(&self, securable: &Securable) -> bool {
        self.access.decides(securable)
    }

    fn refusal_label(&self) -> Option<&'static str> {
        Some("external")
    }
}

