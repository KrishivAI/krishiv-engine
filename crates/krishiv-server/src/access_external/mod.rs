/// How long a prefetched decision answers a later `check` of the same pair: one stage of one
/// analysis, never across statements.
pub const PREFETCH_LIFETIME: Duration = Duration::from_secs(2);

/// How often [`AccessPolicy::version`] asks the service (ADR 0049 §3: at most once a second).
const VERSION_INTERVAL: Duration = Duration::from_secs(1);

/// How long a reported version is trusted without a newer report: past it, [`AccessPolicy::version`]
/// gives an untrusted value (a fresh one per call) until the service answers again.
const VERSION_STALE: Duration = Duration::from_secs(3);

/// What the latest-started call that finished learned about the policy version.
#[derive(Debug, Default)]
struct Noted {
    /// The number of that call ([`ExternalAccess::begin_call`]); 0: none yet.
    seq: u64,
    /// The version it or an earlier call reported (0: none yet).
    version: u64,
    /// Whether it failed or reported 0.
    failed: bool,
    /// When it was recorded.
    at: Option<Instant>,
}

/// The most prefetched decisions a session keeps.
const MEMO_LIMIT: usize = 4 * MAX_ITEMS_PER_CHECK;

/// The server-wide part of the `external` provider: the channel, the token, the last policy
/// version seen and the denial count. Share it (`Arc`) and give each session a
/// [`ExternalPolicy`] from [`Self::policy`].
pub struct ExternalAccess {
    client: AccessPolicyClient<Channel>,
    timeout: Duration,
    token: Option<tonic::metadata::MetadataValue<tonic::metadata::Ascii>>,
    system: bool,
    /// The version the latest-started call reported, and whether that call failed.
    noted: Mutex<Noted>,
    /// Numbers each `Check` and `Version` call when it starts, so an answer that arrives after a
    /// later call's never replaces it.
    call_seq: AtomicU64,
    /// Bumped by every [`AccessPolicy::version`] call that has no trusted version to give.
    untrusted: AtomicU64,
    version_asked: Mutex<Option<Instant>>,
    version_in_flight: AtomicBool,
    /// Woken each time a background version call has finished (its answer recorded, or none).
    /// For tests: only `tests.rs` waits on it (a notification nobody waits for costs nothing).
    version_done: tokio::sync::Notify,
    denials: AtomicU64,
    calls: AtomicU64,
}

