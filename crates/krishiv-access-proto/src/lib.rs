//! The `krishiv.access.v1` protobuf messages (ADR 0049 §3): what Krishiv's `external`
//! access-policy provider sends to a policy service and reads back. Messages only, with no
//! transport: the `tonic` client and server stubs live in `krishiv-server` (feature
//! `access-external`), so an adapter written in Rust can depend on this crate alone.
//!
//! The proto is `proto/krishiv/access/v1/access.proto`; `tools/access-protogen` generates this
//! code. The surface is additive only: fields and enum values are added, never renumbered or
//! removed.
#![forbid(unsafe_code)]
#![expect(
    missing_docs,
    reason = "generated by prost-build from proto/krishiv/access/v1/access.proto, which documents the messages"
)]

include!("access.v1.pb.rs");

/// The most items one `Check` call carries (ADR 0049 §3): a statement with more pairs is split
/// into calls of this size.
pub const MAX_ITEMS_PER_CHECK: usize = 4096;
