// Builds src/tokens/product.css from the brand tokens and the product additions (UI11: one token source for the
// engine console, the Krishiv Console and the site).
//
//   node scripts/build-tokens.mjs [--check]
//
// Inputs: tokens-src/brand-tokens.json (brand, version 2) and tokens-src/product-tokens.json (product additions).
// Output: one CSS file of custom properties. Dark is the default scheme; light applies with
// prefers-color-scheme: light, and data-theme="light" / "dark" on <html> overrides both ways.
// --check exits 1 when the committed product.css differs from what the inputs give.
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const root = new URL("../", import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), "utf8"));
const OUT = new URL("src/tokens/product.css", root);

function colours(brand, product) {
  const toks = [...brand.color.tokens, ...product.color.tokens];
  const by = new Map(toks.map((t) => [t.name, t.value]));
  const res = (v, scheme, seen = new Set()) => {
    const m = /^\{(.+)\}$/.exec(v);
    if (!m) return v;
    if (seen.has(m[1]) || !by.has(m[1])) throw new Error(`token reference {${m[1]}} is unknown or circular`);
    seen.add(m[1]);
    return res(by.get(m[1])[scheme], scheme, seen);
  };
  return toks.map((t) => [t.name, res(t.value.dark, "dark"), res(t.value.light, "light")]);
}

export function build() {
  const brand = read("tokens-src/brand-tokens.json");
  const product = read("tokens-src/product-tokens.json");
  const cols = colours(brand, product);
  const dark = cols.map(([n, d]) => `  --${n}: ${d};`).join("\n");
  const light = cols.map(([n, , l]) => `  --${n}: ${l};`).join("\n");
  const stat = Object.entries(brand.type.families).map(([k, v]) => `  --font-${k}: ${v};`);
  for (const g of [brand.spacing, brand.radius, product.size, product.motion, product.z]) {
    for (const t of g.tokens) stat.push(`  --${t.name}: ${t.value};`);
  }
  for (const s of product.type.styles) {
    stat.push(`  --t-${s.name}: ${s.fontWeight} ${s.fontSize}/${s.lineHeight} var(--font-${s.family});`);
    if ("letterSpacing" in s) stat.push(`  --t-${s.name}-track: ${s.letterSpacing};`);
  }
  // The variable fonts' weight ranges: Display 300-900, Text and Mono 300-700.
  const fonts = [["Display", "display", "300 900"], ["Text", "text", "300 700"], ["Mono", "mono", "300 700"]]
    .map(([name, file, w]) => `@font-face { font-family: "Red Hat ${name}"; src: url("./fonts/redhat${file}-vf.woff2") format("woff2"); font-weight: ${w}; font-display: swap; }`)
    .join("\n");
  const indented = light.split("\n").map((l) => `  ${l}`).join("\n");
  return `/* SPDX-License-Identifier: Apache-2.0 */
/* GENERATED by scripts/build-tokens.mjs from tokens-src/brand-tokens.json (brand v${brand.version})
   and tokens-src/product-tokens.json (product v${product.version}). Do not edit by hand. */
${fonts}

:root {
  color-scheme: dark;
${stat.join("\n")}
}

/* Dark: the default scheme. */
:root, :root[data-theme="dark"] {
${dark}
}

/* Light: by system preference unless the person chose dark, or by choice. */
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
    color-scheme: light;
${indented}
  }
}
:root[data-theme="light"] {
  color-scheme: light;
${light}
}
:root[data-theme="dark"] { color-scheme: dark; }

@media (pointer: coarse), (max-width: 767px) {
  :root { --ctl-h: var(--ctl-h-touch); --row-h: 44px; }
}
@media (prefers-reduced-motion: reduce) {
  :root { --dur-1: 0ms; --dur-2: 0ms; }
}
`;
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const css = build();
  if (process.argv.includes("--check")) {
    let committed = "";
    try {
      committed = readFileSync(OUT, "utf8");
    } catch {}
    if (committed !== css) {
      console.error("src/tokens/product.css differs from its inputs: run `node scripts/build-tokens.mjs` in ui/packages/ui");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, css);
    console.log(`wrote src/tokens/product.css (${css.length} bytes)`);
  }
}
