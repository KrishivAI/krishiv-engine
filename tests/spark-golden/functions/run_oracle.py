"""Run a golden .sql file against a real Spark and write the .out file.

Usage (inside the apache/spark container, with spark-avro and spark-protobuf on --packages):
  spark-submit --packages org.apache.spark:spark-avro_2.13:<v>,org.apache.spark:spark-protobuf_2.13:<v>   (Scala 2.12 artifacts on Spark 3.5.x) \
      run_oracle.py <input.sql> <output.out>

Statements end with ';' at end of line. '--' lines are comments (copied to the output as-is
before the next query). Each statement is executed in order on one session, so SET and
temporary views carry over. Output mirrors SQLQueryTestSuite: query, schema, output (via
cast-to-string rows) or the error (class, SQLSTATE, message parameters, message).
"""

import sys

from pyspark.sql import SparkSession


def split_statements(text):
    stmts, cur = [], []
    for line in text.splitlines():
        if not cur and (line.strip().startswith("--") or not line.strip()):
            continue
        cur.append(line)
        if line.rstrip().endswith(";"):
            stmts.append("\n".join(cur).rstrip()[:-1])
            cur = []
    if cur:
        stmts.append("\n".join(cur))
    return stmts


def describe_error(e):
    je = getattr(e, "java_exception", None) or getattr(e, "_origin", None)
    if je is None:
        return type(e).__name__ + "\nmessage: " + str(e).split("\n")[0]
    out = [je.getClass().getName()]
    cond = None
    for getter in ("getCondition", "getErrorClass"):
        try:
            cond = getattr(je, getter)()
            break
        except Exception:  # noqa: BLE001
            continue
    if cond:
        out.append("errorClass: " + str(cond))
        out.append("sqlState: " + str(je.getSqlState()))
        params = je.getMessageParameters()
        out.append(
            "messageParameters: "
            + str(dict(sorted((str(k), str(v)) for k, v in params.items())))
        )
    out.append("message: " + str(je.getMessage()).split("\n")[0])
    t, depth = je, 0
    while depth < 4:
        c = t.getCause()
        if c is None or c == t:
            break
        out.append(
            "cause: %s: %s"
            % (c.getClass().getName(), str(c.getMessage()).split("\n")[0])
        )
        t, depth = c, depth + 1
    return "\n".join(out)


def main(src, dst):
    spark = (
        SparkSession.builder.appName("golden")
        .config("spark.sql.session.timeZone", "UTC")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("ERROR")
    text = open(src, encoding="utf-8").read()
    res = ["-- Generated by run_oracle.py against Spark " + spark.version, ""]
    for q in split_statements(text):
        res.append("-- !query")
        res.append(q)
        try:
            df = spark.sql(q)
            schema = df.schema.simpleString()
            n = len(df.columns)
            strs = df.toDF(*["c%d" % i for i in range(n)]).selectExpr(
                *["cast(c%d as string)" % i for i in range(n)]
            )
            rows = [
                "\t".join("NULL" if v is None else v for v in r) for r in strs.collect()
            ]
            res.append("-- !query schema")
            res.append(schema)
            res.append("-- !query output")
            res.extend(str(r) for r in rows)
        except Exception as e:  # noqa: BLE001
            res.append("-- !query schema")
            res.append("struct<>")
            res.append("-- !query output")
            res.append(describe_error(e))
        res.append("")
        res.append("")
    open(dst, "w", encoding="utf-8").write("\n".join(res))


main(sys.argv[1], sys.argv[2])
