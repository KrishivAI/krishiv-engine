"""Runs the protobuf golden .sql files on Spark 3.5.x, which has no SQL `from_protobuf` / `to_protobuf`.

Every `from_protobuf(...)` / `to_protobuf(...)` call in a statement is rebuilt through the DataFrame API
(`pyspark.sql.protobuf.functions`, the only form 3.5 has), exposed as column `__pbN` of a one-row view `__pbv`,
and the rest of the statement runs as SQL against that view. A constant binary descriptor goes through `binaryDescriptorSet`; a descriptor that is
neither a path nor a binary literal is reported as `UNSUPPORTED_ON_35`. Result column names differ from the SQL runs
(`__pbN`); values and errors are comparable.

Usage: spark-submit --packages org.apache.spark:spark-protobuf_2.12:3.5.7 run_oracle_df.py <input.sql> <output.out>
"""

import re
import sys

from pyspark.sql import SparkSession
from pyspark.sql import functions as F
from pyspark.sql.protobuf.functions import from_protobuf, to_protobuf


def split_statements(text):
    stmts, cur = [], []
    for line in text.splitlines():
        if not cur and (line.strip().startswith("--") or not line.strip()):
            continue
        cur.append(line)
        if line.rstrip().endswith(";"):
            stmts.append("\n".join(cur).rstrip()[:-1])
            cur = []
    if cur:
        stmts.append("\n".join(cur))
    return stmts


def describe_error(e):
    je = getattr(e, "java_exception", None) or getattr(e, "_origin", None)
    if je is None:
        return type(e).__name__ + "\nmessage: " + str(e).split("\n")[0]
    out = [je.getClass().getName()]
    cond = None
    for getter in ("getErrorClass", "getCondition"):
        try:
            cond = getattr(je, getter)()
            break
        except Exception:  # noqa: BLE001
            continue
    if cond:
        out.append("errorClass: " + str(cond))
        out.append("sqlState: " + str(je.getSqlState()))
        params = je.getMessageParameters()
        out.append(
            "messageParameters: "
            + str(dict(sorted((str(k), str(v)) for k, v in params.items())))
        )
    out.append("message: " + str(je.getMessage()).split("\n")[0])
    t, depth = je, 0
    while depth < 4:
        c = t.getCause()
        if c is None or c == t:
            break
        out.append(
            "cause: %s: %s"
            % (c.getClass().getName(), str(c.getMessage()).split("\n")[0])
        )
        t, depth = c, depth + 1
    return "\n".join(out)


def scan_call(s, start):
    """Returns the index after the `)` closing the call whose `(` is at s[start]."""
    depth, i, q = 0, start, False
    while i < len(s):
        ch = s[i]
        if q:
            if ch == "\\":
                i += 1
            elif ch == "'":
                q = False
        elif ch == "'":
            q = True
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    raise ValueError("unbalanced call")


def split_args(body):
    args, depth, q, cur, i = [], 0, False, [], 0
    while i < len(body):
        ch = body[i]
        if q:
            cur.append(ch)
            if ch == "\\":
                i += 1
                cur.append(body[i])
            elif ch == "'":
                q = False
        elif ch == "'":
            q = True
            cur.append(ch)
        elif ch in "([":
            depth += 1
            cur.append(ch)
        elif ch in ")]":
            depth -= 1
            cur.append(ch)
        elif ch == "," and depth == 0:
            args.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
        i += 1
    args.append("".join(cur).strip())
    return args


def unquote(a):
    if a.startswith("'") and a.endswith("'"):
        return a[1:-1]
    return None


def main(src, dst):
    spark = (
        SparkSession.builder.appName("golden-df")
        .config("spark.sql.session.timeZone", "UTC")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("ERROR")
    res = [
        "-- Generated by run_oracle_df.py (DataFrame API) against Spark "
        + spark.version,
        "",
    ]
    for q in split_statements(open(src, encoding="utf-8").read()):
        res.append("-- !query")
        res.append(q)
        try:
            text, cols, n, pos = q, [], 0, 0
            if re.match(r"\s*set\s", q, re.IGNORECASE):
                df = spark.sql(q)
            else:
                out = []
                for m in re.finditer(r"\b(from|to)_protobuf\(", q):
                    if m.start() < pos:
                        continue
                    end = scan_call(q, m.end() - 1)
                    args = split_args(q[m.end() : end - 1])
                    kind = m.group(1)
                    data = F.expr(args[0])
                    msg = unquote(args[1])
                    third = args[2] if len(args) > 2 else None
                    fourth = args[3] if len(args) > 3 else None
                    path, binary, opts = None, None, {}
                    if third is not None and third.lower().startswith("map("):
                        fourth, third = third, None
                    if third is not None:
                        path = unquote(third)
                        if path is None:
                            # A constant binary descriptor goes through `binaryDescriptorSet`.
                            value = spark.sql("select " + third).collect()[0][0]
                            if not isinstance(value, (bytes, bytearray)):
                                raise NotImplementedError(
                                    "UNSUPPORTED_ON_35: descriptor argument is neither a path nor binary literal"
                                )
                            binary = bytes(value)
                    if fourth is not None:
                        opts = dict(spark.sql("select " + fourth).collect()[0][0] or {})
                    fn = from_protobuf if kind == "from" else to_protobuf
                    cols.append(
                        fn(
                            data,
                            msg,
                            descFilePath=path,
                            options=opts,
                            binaryDescriptorSet=binary,
                        ).alias("__pb%d" % n)
                    )
                    out.append(q[pos : m.start()] + "__pb%d" % n)
                    pos = end
                    n += 1
                out.append(q[pos:])
                text = "".join(out)
                spark.range(1).select(*cols).createOrReplaceTempView("__pbv")
                df = spark.sql(text + " from __pbv") if cols else spark.sql(text)
            schema = df.schema.simpleString()
            k = len(df.columns)
            strs = df.toDF(*["c%d" % i for i in range(k)]).selectExpr(
                *["cast(c%d as string)" % i for i in range(k)]
            )
            rows = [
                "\t".join("NULL" if v is None else v for v in r) for r in strs.collect()
            ]
            res.append("-- !query schema")
            res.append(schema)
            res.append("-- !query output")
            res.extend(str(r) for r in rows)
        except NotImplementedError as e:
            res.append("-- !query schema")
            res.append("struct<>")
            res.append("-- !query output")
            res.append(str(e))
        except Exception as e:  # noqa: BLE001
            res.append("-- !query schema")
            res.append("struct<>")
            res.append("-- !query output")
            res.append(describe_error(e))
        res.append("")
        res.append("")
    open(dst, "w", encoding="utf-8").write("\n".join(res))


main(sys.argv[1], sys.argv[2])
