"""Prints the exact result schema of from_protobuf (nullability included) through the DataFrame API.

Usage (in the apache/spark container, spark-protobuf on --packages):
  spark-submit run_schema_nullability.py <out-file>
The DataFrame API is the only form that exists on Spark 3.5.x, so one script covers 3.5.7 .. 4.3.0.
"""

import sys

from pyspark.sql import SparkSession
from pyspark.sql import functions as F
from pyspark.sql.protobuf.functions import from_protobuf
from pyspark.sql.types import ArrayType, MapType, StructType

G = "/golden/from_to_protobuf/fixtures/"
D0, DT, DP = (
    G + "krishiv_golden.desc",
    G + "krishiv_golden_types.desc",
    G + "krishiv_golden_p2.desc",
)
TN, PN = "krishiv.golden.types.", "krishiv.golden.p2."
R2 = {"recursive.fields.max.depth": "2"}
CASES = [
    ("Scalars", "krishiv.golden.Scalars", D0, {}),
    (
        "Scalars enums.as.ints upcast",
        "krishiv.golden.Scalars",
        D0,
        {"enums.as.ints": "true", "upcast.unsigned.ints": "true"},
    ),
    ("Outer", "krishiv.golden.Outer", D0, {}),
    ("Node depth2", "krishiv.golden.Node", D0, R2),
    ("Wkt", TN + "Wkt", DT, {}),
    (
        "Wkt unwrap",
        TN + "Wkt",
        DT,
        {"unwrap.primitive.wrapper.types": "true", "upcast.unsigned.ints": "true"},
    ),
    ("Wkt any-json", TN + "Wkt", DT, {"convert.any.fields.to.json": "true"}),
    ("Wkt retain-empty", TN + "Wkt", DT, {"retain.empty.message.types": "true"}),
    ("HasEmpty", TN + "HasEmpty", DT, {}),
    ("HasEmpty retain", TN + "HasEmpty", DT, {"retain.empty.message.types": "true"}),
    ("Rec depth2", TN + "Rec", DT, R2),
    ("Rec depth3", TN + "Rec", DT, {"recursive.fields.max.depth": "3"}),
    ("MA depth2", TN + "MA", DT, R2),
    ("Kinds depth2", TN + "Kinds", DT, R2),
    ("P2", PN + "P2", DP, {"mode": "PERMISSIVE"}),
    ("P2Required", PN + "P2Required", DP, {"mode": "PERMISSIVE"}),
    ("P2Nest", PN + "P2Nest", DP, {"mode": "PERMISSIVE"}),
]


def render(dt):
    if isinstance(dt, StructType):
        parts = [
            f"{f.name}:{render(f.dataType)}{'' if f.nullable else ' NOT NULL'}"
            for f in dt.fields
        ]
        return "struct<" + ", ".join(parts) + ">"
    if isinstance(dt, ArrayType):
        return (
            f"array<{render(dt.elementType)}{'' if dt.containsNull else ' NOT NULL'}>"
        )
    if isinstance(dt, MapType):
        return f"map<{render(dt.keyType)}, {render(dt.valueType)}{'' if dt.valueContainsNull else ' NOT NULL'}>"
    return dt.simpleString()


def main(dst):
    spark = (
        SparkSession.builder.appName("schema")
        .config("spark.sql.session.timeZone", "UTC")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("ERROR")
    res = [
        "-- Generated by run_schema_nullability.py against Spark " + spark.version,
        "",
    ]
    for ext in ("false", "true"):
        spark.conf.set("spark.sql.function.protobufExtensions.enabled", ext)
        for label, msg, desc, opts in CASES:
            if ext == "true" and not label.startswith("P2"):
                continue
            res.append(f"-- {label} (protobufExtensions.enabled={ext}) options={opts}")
            try:
                df = spark.range(1).select(F.lit(b"").alias("b"))
                out = df.select(
                    from_protobuf("b", msg, descFilePath=desc, options=opts).alias("r")
                )
                res.append("root nullable: " + str(out.schema["r"].nullable))
                res.append(render(out.schema["r"].dataType))
            except Exception as e:  # noqa: BLE001
                res.append("ERROR " + str(e).split("\n")[0][:300])
            res.append("")
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("\n".join(res))


main(sys.argv[1])
