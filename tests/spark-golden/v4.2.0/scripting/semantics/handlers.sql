-- Conditions and handlers, design note section 2.4.
-- CASE sqlexception_catches
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'caught' AS c; SELECT 1/0; SELECT 'after' AS a; END;
-- CASE declared_condition_sqlstate_does_not_catch
BEGIN DECLARE c CONDITION FOR SQLSTATE '22012'; DECLARE EXIT HANDLER FOR c SELECT 'caught' AS r; SELECT 1/0; END;
-- CASE declared_condition_same_name_as_error_class
BEGIN DECLARE DIVIDE_BY_ZERO CONDITION; DECLARE EXIT HANDLER FOR DIVIDE_BY_ZERO SELECT 'caught' AS r; SELECT 1/0; END;
-- CASE handler_for_error_class_name
BEGIN DECLARE EXIT HANDLER FOR DIVIDE_BY_ZERO SELECT 'caught' AS r; SELECT 1/0; END;
-- CASE handler_for_class_prefix
BEGIN DECLARE EXIT HANDLER FOR UNRESOLVED_COLUMN SELECT 'caught' AS r; SELECT nope; END;
-- CASE handler_for_sqlstate
BEGIN DECLARE EXIT HANDLER FOR SQLSTATE '22012' SELECT 'caught' AS r; SELECT 1/0; END;
-- CASE handler_for_sqlstate_other_state
BEGIN DECLARE EXIT HANDLER FOR SQLSTATE '22003' SELECT 'caught' AS r; SELECT 1/0; END;
-- CASE handler_not_found_does_not_catch_error
BEGIN DECLARE EXIT HANDLER FOR NOT FOUND SELECT 'caught' AS r; SELECT 1/0; END;
-- CASE specific_beats_sqlexception_same_scope
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'generic' AS r; DECLARE EXIT HANDLER FOR DIVIDE_BY_ZERO SELECT 'specific' AS r; SELECT 1/0; END;
-- CASE sqlstate_beats_sqlexception
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'generic' AS r; DECLARE EXIT HANDLER FOR SQLSTATE '22012' SELECT 'state' AS r; SELECT 1/0; END;
-- CASE name_beats_sqlstate
BEGIN DECLARE EXIT HANDLER FOR SQLSTATE '22012' SELECT 'state' AS r; DECLARE EXIT HANDLER FOR DIVIDE_BY_ZERO SELECT 'name' AS r; SELECT 1/0; END;
-- CASE inner_error_goes_to_outer_handler
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'outer' AS r; BEGIN SELECT 1/0; END; SELECT 'after' AS a; END;
-- CASE inner_handler_wins
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'outer' AS r; BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'inner' AS r; SELECT 1/0; END; SELECT 'after' AS a; END;
-- CASE raise_error_sqlexception
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'caught' AS r; SELECT raise_error('x'); END;
-- CASE raise_error_by_class
BEGIN DECLARE EXIT HANDLER FOR USER_RAISED_EXCEPTION SELECT 'caught' AS r; SELECT raise_error('x'); END;
-- CASE raise_error_by_sqlstate
BEGIN DECLARE EXIT HANDLER FOR SQLSTATE 'P0001' SELECT 'caught' AS r; SELECT raise_error('x'); END;
-- CASE handler_covers_declare_default
BEGIN DECLARE x INT DEFAULT 1/0; DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'caught' AS r; SELECT 'body' AS b; END;
-- CASE handler_covers_inner_declare_default
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'caught' AS r; BEGIN DECLARE y INT DEFAULT 1/0; SELECT 'inner' AS b; END; END;
-- CASE handler_covers_if_condition
BEGIN DECLARE EXIT HANDLER FOR INVALID_BOOLEAN_STATEMENT SELECT 'caught' AS r; IF 1 THEN SELECT 'then'; END IF; END;
-- CASE handler_covers_while_condition
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'caught' AS r; WHILE 1 DO SELECT 'body'; END WHILE; END;
-- CASE ansi_off_no_handler
SET spark.sql.ansi.enabled = false;
-- next
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'caught' AS r; SELECT 1/0 AS q; END;
-- CASE exit_continues_after_declaring_compound
BEGIN DECLARE x INT DEFAULT 0; lbl: BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SET x = 1; SET x = 2; SELECT 1/0; SET x = 3; END lbl; SELECT x; END;
-- CASE outermost_handler_ends_script
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'caught' AS r; SELECT 1/0; SELECT 'never' AS n; END;
-- CASE handler_without_result_keeps_earlier_result
BEGIN DECLARE x INT DEFAULT 0; DECLARE EXIT HANDLER FOR SQLEXCEPTION SET x = 1; SELECT 'first' AS f; SELECT 1/0; END;
-- CASE handler_sees_variables_at_error
BEGIN DECLARE x INT DEFAULT 1; DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT x; SET x = 2; SELECT 1/0; END;
-- CASE handler_does_not_see_inner_locals
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT y; BEGIN DECLARE y INT DEFAULT 5; SELECT 1/0; END; END;
-- CASE leave_out_of_handler_body_does_not_leave_label
BEGIN DECLARE x INT DEFAULT 0; o: BEGIN i: BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN SET x = 1; LEAVE o; END; SELECT 1/0; END i; SET x = 2; END o; SELECT x; END;
-- CASE handler_body_compound
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN DECLARE m STRING DEFAULT 'm'; SELECT m AS r; END; SELECT 1/0; END;
-- CASE handler_body_single_set
BEGIN DECLARE x INT DEFAULT 0; DECLARE EXIT HANDLER FOR SQLEXCEPTION SET x = 5; SELECT 1/0; END;
-- CASE handler_body_single_insert
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION INSERT INTO s VALUES (77); SELECT 1/0; END;
-- next
SELECT * FROM s;
-- CASE error_in_handler_body_inner_handler
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'inner' AS r; SELECT 1/0; END; SELECT raise_error('first'); END;
-- CASE error_in_handler_body_outer_scope_handles
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'outer' AS r; BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 1/0; SELECT raise_error('first'); END; END;
-- CASE error_in_handler_body_own_compound_does_not_handle
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT raise_error('second'); SELECT raise_error('first'); END;
-- CASE update_parquet_in_script_caught
BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SELECT 'caught' AS r; UPDATE s SET i = 1; END;
-- CASE update_parquet_in_script_class
BEGIN UPDATE s SET i = 1; END;
-- CASE handler_for_multiple_names
BEGIN DECLARE EXIT HANDLER FOR DIVIDE_BY_ZERO, UNRESOLVED_COLUMN SELECT 'caught' AS r; SELECT nope; END;
-- CASE handler_for_multiple_sqlstates
BEGIN DECLARE EXIT HANDLER FOR SQLSTATE '22003', SQLSTATE '22012' SELECT 'caught' AS r; SELECT 1/0; END;
-- CASE error_class_visible_cast_invalid
BEGIN DECLARE EXIT HANDLER FOR CAST_INVALID_INPUT SELECT 'caught' AS r; SELECT CAST('abc' AS INT); END;
-- CASE error_class_visible_overflow
BEGIN DECLARE EXIT HANDLER FOR ARITHMETIC_OVERFLOW SELECT 'caught' AS r; SELECT 2147483647 + 1; END;
-- CASE no_handler_unhandled_after_result
BEGIN SELECT 'first' AS f; SELECT 1/0; END;
-- CASE exit_handler_in_loop_body_compound
BEGIN DECLARE i INT DEFAULT 0; WHILE i < 3 DO BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SET i = i + 10; SET i = i + 1; SELECT 1/0; END; END WHILE; SELECT i; END;
-- CASE exit_handler_in_loop_body_trace
BEGIN DECLARE i INT DEFAULT 0; WHILE i < 3 DO BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION INSERT INTO s VALUES (100 + i); INSERT INTO s VALUES (i); SET i = i + 1; SELECT 1/0; END; END WHILE; INSERT INTO s VALUES (999); SELECT 'end' AS e; END;
-- next
SELECT i FROM s ORDER BY i;
-- CASE exit_handler_in_loop_body_no_error
BEGIN DECLARE i INT DEFAULT 0; WHILE i < 3 DO BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SET i = 50; SET i = i + 1; END; END WHILE; SELECT i; END;
-- CASE exit_handler_in_nested_compound_then_select
BEGIN DECLARE i INT DEFAULT 0; BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SET i = 10; SELECT 1/0; END; SELECT i; END;
-- CASE exit_handler_in_if_nested_compound
BEGIN DECLARE i INT DEFAULT 0; IF true THEN BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION SET i = 10; SELECT 1/0; END; END IF; SELECT i; END;
-- CASE exit_in_if_body_compound_then_more
-- NOTE the handler's compound sits inside an IF body: what runs afterwards (rows of s) is the point.
BEGIN IF true THEN BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION INSERT INTO s VALUES (1); SELECT 1/0; END; INSERT INTO s VALUES (2); END IF; INSERT INTO s VALUES (3); SELECT 'end' AS e; END;
-- next
SELECT i FROM s ORDER BY i;
-- CASE exit_in_labelled_compound_then_more
BEGIN a: BEGIN BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION INSERT INTO s VALUES (1); SELECT 1/0; END; INSERT INTO s VALUES (2); END a; INSERT INTO s VALUES (3); SELECT 'end' AS e; END;
-- next
SELECT i FROM s ORDER BY i;
-- CASE exit_in_for_body_compound_then_more
BEGIN FOR r AS SELECT id FROM range(3) DO BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION INSERT INTO s VALUES (10 + r.id); SELECT 1/0; END; END FOR; INSERT INTO s VALUES (3); SELECT 'end' AS e; END;
-- next
SELECT i FROM s ORDER BY i;
-- CASE exit_in_while_body_compound_two_statements_after
BEGIN DECLARE i INT DEFAULT 0; WHILE i < 3 DO SET i = i + 1; BEGIN DECLARE EXIT HANDLER FOR SQLEXCEPTION INSERT INTO s VALUES (i); SELECT 1/0; END; INSERT INTO s VALUES (50 + i); END WHILE; INSERT INTO s VALUES (999); END;
-- next
SELECT i FROM s ORDER BY i;
