"""Renders docs/guides/pyspark-migration.md (P3-T074) from the compatibility data:
the function matrix, its workarounds and the known-differences page. Nothing in the
tables is hand-written. Run from the repo root; `--check` diffs only (exit 1 on drift)."""

import json
import pathlib
import re
import sys

CC = pathlib.Path("crates/krishiv-cli/src/check_compat")
KD = pathlib.Path("docs/concepts/known-differences.md")
OUT = pathlib.Path("docs/guides/pyspark-migration.md")
FN_PAGE = "../reference/sql/functions/{}.md"


def slug(heading: str) -> str:
    """GitHub's heading anchor (the same rule as check_docs_links.py)."""
    return re.sub(r"[^\w\- ]", "", heading.strip().lower()).replace(" ", "-")


def differences() -> list[tuple[str, str]]:
    """(heading, anchor) of each `##` section of the known-differences page; a repeated heading gets -1, -2."""
    seen: dict[str, int] = {}
    rows = []
    for m in re.finditer(
        r"^## (.+)$", re.sub(r"^```.*?^```", "", KD.read_text(encoding="utf-8"), flags=re.S | re.M), re.M
    ):
        base = slug(m.group(1))
        n = seen.get(base, 0)
        seen[base] = n + 1
        rows.append((m.group(1).strip(), base if n == 0 else f"{base}-{n}"))
    return rows


def render() -> str:
    matrix = json.loads((CC / "functions.json").read_text(encoding="utf-8"))
    alts = json.loads((CC / "alternatives.json").read_text(encoding="utf-8"))
    missing = sorted(k for k, v in matrix.items() if v != "supported")
    o = [
        "---",
        "description: Move a PySpark job to Krishiv: unsupported functions, workarounds and behaviour differences.",
        "---",
        "",
        "<!-- SPDX-License-Identifier: Apache-2.0 -->",
        "<!-- Generated by tests/scripts/gen_migration_guide.py from the compatibility data; do not edit. -->",
        "# Migrate a PySpark job to Krishiv",
        "",
        "Krishiv keeps the PySpark API: `krishiv.session()` returns a "
        "`SparkSession`-style object, and `spark.sql`, `spark.read`,",
        "DataFrames and `pyspark.sql.functions`-style functions behave as in Spark. This "
        "page lists what differs and what to do.",
        "The tables below are generated from the same data `krishiv check-compat` reads, so they cannot drift from it.",
        "",
        "Krishiv needs Python 3.11 or newer, the floor of the Spark 4.3 Python client; "
        "the examples here run on 3.11 to 3.14.",
        "",
        "## Step 1: install and switch the session",
        "",
        "```bash",
        'pip install "krishiv[pyarrow]"',
        "```",
        "",
        "`collect()` and `toArrow()` return Arrow data, so the `pyarrow` extra is needed for them.",
        "",
        "```python",
        "import krishiv",
        "from krishiv.sql import functions as F",
        "",
        "spark = krishiv.session()  # replaces SparkSession.builder.getOrCreate()",
        'df = spark.createDataFrame([("east", 10.0), ("west", 20.0), ("east", 5.5)], ["region", "amount"])',
        'out = df.groupBy("region").agg(F.sum("amount").alias("revenue")).orderBy("region")',
        'assert [tuple(r) for r in out.collect()] == [("east", 15.5), ("west", 20.0)]',
        "```",
        "",
        "## Step 2: scan your project",
        "",
        "`krishiv check-compat` reads `.py`, `.sql` and `.ipynb` files without running "
        "them and lists the functions below that",
        "your code calls (see [check-compat](check-compat.md)).",
        "",
        "```bash",
        "krishiv check-compat .",
        "```",
        "",
        f"## Spark functions Krishiv does not run yet ({len(missing)})",
        "",
        "A name that is not in the data is reported as unknown and is not supported. A "
        "workaround is given only where one exists;",
        "an empty cell means there is none yet.",
        "",
        "| Function | Status | Workaround |",
        "| --- | --- | --- |",
    ]
    for name in missing:
        alt = alts.get(name, "").replace("|", "\\|")
        o.append(f"| [`{name}`]({FN_PAGE.format(name)}) | {matrix[name]} | {alt} |")
    o += [
        "",
        "## Behaviour that differs from Spark",
        "",
        "Each row links to the full description in [known differences](../concepts/known-differences.md).",
        "",
        "| Difference |",
        "| --- |",
    ]
    for head, anchor in differences():
        o.append(f"| [{head}](../concepts/known-differences.md#{anchor}) |")
    o += [
        "",
        "## Where it runs",
        "",
        "Krishiv has three deployment modes: embedded (in your Python process, as above), single-node and distributed.",
        "Single-node is one `krishiv server` process that PySpark and other clients reach over Spark Connect; "
        "see [Deployment](deploy.md).",
        "",
        "## Step 3: check the result",
        "",
        "Run the same job on both engines over a small input and compare. For plans and "
        "per-operator cost use `df.explain(analyze=True)`",
        "([EXPLAIN ANALYZE](../reference/explain-analyze.md)).",
        "",
    ]
    return "\n".join(o)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT)
