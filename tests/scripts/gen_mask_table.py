#!/usr/bin/env python3
"""Generate the Spark `mask()` character-class fixture for the string kernels.

Queries a REAL Spark (never from memory) with `mask(s, 'U', 'l', 'd', 'o')` over every Unicode scalar value
(U+0000 to U+10FFFF without surrogates), 10,000 code points per string, and records which of the four
classes (upper, lower, digit, other) Spark assigns to each. Spark classifies UTF-16 code units, so every
supplementary scalar (U+10000 and up) is two `other` units; the script asserts that, and the fixture covers
the basic multilingual plane only. The fixture lists the code points whose class differs from the ASCII
rule (`A-Z` upper, `a-z` lower, `0-9` digit, everything else other) as inclusive ranges
`[first, last, class]`, class being one of "U", "l", "d". `--rust PATH` also writes the kernel's table:
per class, runs `(first, last, step)` (every `step`-th code point, step 1 or 2). Usage (from repo root):

    SPARK_HOME=$HOME/krishiv-data/tmp/spark-home-stub uv run --no-project --python 3.12 \\
        --with 'pyspark-client==4.2.0' python tests/scripts/gen_mask_table.py sc://127.0.0.1:15012 \\
        --rust crates/krishiv-kernels/src/string/mask_table.rs \\
        > tests/fixtures/spark-4.2.0/mask-classes.json

The first argument is the Spark Connect URL; the fixture goes to stdout.
"""

import json
import sys

from pyspark.sql import SparkSession

CHUNK = 10_000


def ascii_class(cp: int) -> str:
    if 0x41 <= cp <= 0x5A:
        return "U"
    if 0x61 <= cp <= 0x7A:
        return "l"
    if 0x30 <= cp <= 0x39:
        return "d"
    return "o"


def runs(cps: list[int]) -> list[tuple[int, int, int]]:
    """Greedy `(first, last, step)` runs (step 1 or 2) covering the sorted `cps` exactly."""
    out: list[tuple[int, int, int]] = []
    i = 0
    while i < len(cps):
        best_end, best_step = i, 1
        for step in (1, 2):
            j = i
            while j + 1 < len(cps) and cps[j + 1] - cps[j] == step:
                j += 1
            if j > best_end:
                best_end, best_step = j, step
        out.append((cps[i], cps[best_end], best_step))
        i = best_end + 1
    return out


def write_rust(path: str, ranges: list[list], version: str) -> None:
    names = {"U": "UPPER", "l": "LOWER", "d": "DIGIT"}
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        f"//! Generated by `tests/scripts/gen_mask_table.py` from Spark {version}; do not edit.",
        "//!",
        "//! The basic-multilingual-plane scalars whose `mask()` class is not the ASCII rule, per class as",
        "//! `(first, last, step)` runs (every `step`-th code point from `first` to `last`), sorted and",
        "//! disjoint within a class.",
    ]
    for cls, name in names.items():
        cps = sorted(c for a, b, k in ranges if k == cls for c in range(a, b + 1))
        table = runs(cps)
        lines += ["", f"pub(super) static {name}: [(u32, u32, u32); {len(table)}] = ["]
        lines += [f"    ({a:#06x}, {b:#06x}, {st})," for a, b, st in table]
        lines.append("];")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main() -> None:
    remote = sys.argv[1] if len(sys.argv) > 1 else "sc://127.0.0.1:15012"
    spark = SparkSession.builder.remote(remote).getOrCreate()
    scalars = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]
    chunks = [scalars[i : i + CHUNK] for i in range(0, len(scalars), CHUNK)]
    df = spark.createDataFrame([(i, "".join(map(chr, ch))) for i, ch in enumerate(chunks)], "i int, s string")
    rows = {r.i: r.m for r in df.selectExpr("i", "mask(s, 'U', 'l', 'd', 'o') m").collect()}
    ranges: list[list] = []
    for i, ch in enumerate(chunks):
        masked = iter(rows[i])
        for cp in ch:
            if cp >= 0x10000:
                # Spark masks UTF-16 code units: a supplementary scalar is two `other` units.
                units = (next(masked), next(masked))
                assert units == ("o", "o"), cp
                continue
            cls = next(masked)
            assert cls in "Ulodo", (cp, cls)
            if cls == ascii_class(cp):
                continue
            if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == cls:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp, cls])
        assert next(masked, None) is None, i
    if "--rust" in sys.argv:
        write_rust(sys.argv[sys.argv.index("--rust") + 1], ranges, spark.version)
    json.dump(
        {"spark_version": spark.version, "scalars": len(scalars), "ranges": ranges},
        sys.stdout,
        sort_keys=True,
        separators=(",", ":"),
    )
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
