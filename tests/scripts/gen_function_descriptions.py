"""Generate the text `DESCRIBE FUNCTION [EXTENDED]` prints for Spark's built-in functions (SQL-13).

Everything comes from executing Spark 4.2.0 (`apache/spark:4.2.0`) in a throw-away container: for each name
of `crates/krishiv-functions/vendored/spark-functions.tsv`, `DESCRIBE FUNCTION EXTENDED` is run and its
rows kept (`Function:`, `Class:`, `Usage:` and, when the function has one, `Extended Usage:`). A name the
release does not have (added in a later line) is left out.

Output: `crates/krishiv-functions/vendored/spark-function-descriptions.tsv`: `name<TAB>row<TAB>row...`,
sorted by name, `\\` written `\\\\` and a line feed `\\n` inside a row.

Usage (from the repo root; needs Docker and the image):

    python3 tests/scripts/gen_function_descriptions.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "crates/krishiv-functions/vendored/spark-functions.tsv"
OUT = ROOT / "crates/krishiv-functions/vendored/spark-function-descriptions.tsv"
IMAGE = "apache/spark:4.2.0"

PROBE = """
import json
from pyspark.sql import SparkSession
spark = SparkSession.builder.master("local[1]").config("spark.ui.enabled", "false").getOrCreate()
out = {}
for n in open("/work/names.txt").read().split("\\n"):
    if not n:
        continue
    q = "`" + n.replace("`", "``") + "`"
    try:
        out[n] = [r[0] for r in spark.sql("DESCRIBE FUNCTION EXTENDED " + q).collect()]
    except Exception:
        pass
json.dump(out, open("/work/out.json", "w"))
"""


def escape(row: str) -> str:
    return row.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", "\\t")


def main() -> int:
    names = [line.split("\t")[0] for line in CATALOG.read_text().splitlines() if line and not line.startswith("#")]
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        (work / "names.txt").write_text("\n".join(names) + "\n")
        (work / "probe.py").write_text(PROBE)
        subprocess.run(
            [
                "docker",
                "run",
                "--rm",
                "-u",
                "0",
                "-v",
                f"{work}:/work",
                IMAGE,
                "/opt/spark/bin/spark-submit",
                "/work/probe.py",
            ],
            check=True,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        described = json.loads((work / "out.json").read_text())
    lines = [
        "# generated by tests/scripts/gen_function_descriptions.py from Spark 4.2.0; "
        "columns: name, then the DESCRIBE FUNCTION EXTENDED rows",
    ]
    for name in sorted(described):
        lines.append("\t".join([name, *(escape(r) for r in described[name])]))
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(described)} of {len(names)} names described", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
