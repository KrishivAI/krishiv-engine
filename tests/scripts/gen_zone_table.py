#!/usr/bin/env python3
"""Turn the Spark zone-name fixture (`gen_zone_names.py`) into the kernel table.

Usage (from repo root):

    python3 tests/scripts/gen_zone_table.py --out crates/krishiv-kernels/src/datetime_pattern/zone_names.rs
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

FIXTURE = "tests/fixtures/spark-4.2.0/zone-names.json"


def lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixture", default=FIXTURE)
    ap.add_argument("--out", default="crates/krishiv-kernels/src/datetime_pattern/zone_names.rs")
    args = ap.parse_args()
    fx = json.loads(Path(args.fixture).read_text(encoding="utf-8"))
    # Java's legacy `SystemV/*` ids are not in the tz database; no Krishiv zone resolves to them.
    zones = {k: v for k, v in fx["zones"].items() if not k.startswith("SystemV/")}
    groups = sorted({tuple(z["names"]) for z in zones.values()})
    index = {g: i for i, g in enumerate(groups)}
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// @generated by tests/scripts/gen_zone_table.py; do not edit.",
        f"//! The `z` and `zzzz` names Spark {fx['spark_version']} prints for region zones (Java's tables, not the",
        "//! tz database's abbreviations).",
        "",
        "/// `[standard short, standard full, daylight short, daylight full]`.",
        "pub(super) const NAMES: &[[&str; 4]] = &[",
    ]
    out += [f"    [{', '.join(lit(n) for n in g)}]," for g in groups]
    out += [
        "];",
        "",
        "/// Zone id to an index of [`NAMES`], sorted by id.",
        "pub(super) const ZONES: &[(&str, u8)] = &[",
    ]
    out += [f"    ({lit(z)}, {index[tuple(zones[z]['names'])]})," for z in sorted(zones)]
    out.append("];")
    Path(args.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {len(zones)} zones / {len(groups)} name sets -> {args.out}")


if __name__ == "__main__":
    main()
