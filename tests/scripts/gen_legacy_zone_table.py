"""Turn the LEGACY parser fixture (`gen_legacy_zone_strings.py`) into the kernel table.

Usage (from repo root):

    python3 tests/scripts/gen_legacy_zone_table.py
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

FIXTURE = "tests/fixtures/spark-4.2.0/legacy-zone-strings.json"
OUT = "crates/krishiv-kernels/src/datetime_pattern/legacy_zones.rs"
PROBES = "crates/krishiv-kernels/tests/fixtures/legacy_zone_probes.rs"


def lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--fixture", default=FIXTURE)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--probes", default=PROBES)
    args = ap.parse_args()
    fx = json.loads(Path(args.fixture).read_text(encoding="utf-8"))
    # The search takes the first row with a matching name, so a row whose four names repeat an earlier
    # row's is never found: drop it.
    rows, seen = [], set()
    for zid, long_std, short_std, long_dst, short_dst, raw_ms, dst_ms in fx["zone_strings"]:
        names = (long_std or "", short_std or "", long_dst or "", short_dst or "")
        if names in seen:
            continue
        seen.add(names)
        rows.append((zid, names, raw_ms // 1000, dst_ms // 1000))
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// @generated by tests/scripts/gen_legacy_zone_table.py; do not edit.",
        f"//! What `SimpleDateFormat` (`Locale.US`) reads under LEGACY, from the JVM of Spark {fx['spark_version']}",
        f"//! (Java {fx['java_version']}): its zone strings and the decimal digits of numeric fields.",
        "",
        "/// A row of `DateFormatSymbols.getZoneStrings()`, in the JVM's order (rows repeating an earlier",
        "/// row's names dropped).",
        "pub(super) struct ZoneStrings {",
        "    /// The zone id.",
        "    pub id: &'static str,",
        "    /// Long standard, short standard, long daylight, short daylight name.",
        "    pub names: [&'static str; 4],",
        "    /// `TimeZone.getRawOffset()` of the id, in seconds.",
        "    pub raw: i32,",
        "    /// `TimeZone.getDSTSavings()` of the id, in seconds.",
        "    pub dst: i32,",
        "}",
        "",
        "pub(super) const ZONE_STRINGS: &[ZoneStrings] = &[",
    ]
    for zid, names, raw, dst in rows:
        out += [
            "    ZoneStrings {",
            f"        id: {lit(zid)},",
            f"        names: [{', '.join(lit(n) for n in names)}],",
            f"        raw: {raw},",
            f"        dst: {dst},",
            "    },",
        ]
    out += [
        "];",
        "",
        "/// The zero of every run of ten decimal digits `Character.digit(c, 10)` reads in the Basic",
        "/// Multilingual Plane, increasing.",
        "pub(super) const DIGIT_ZEROS: &[u32] = &[",
    ]
    out += [f"    0x{z:04X}," for z in fx["digit_zeros"]]
    out += ["];", ""]
    Path(args.out).write_text("\n".join(out), encoding="utf-8")
    probes = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// @generated by tests/scripts/gen_legacy_zone_table.py; do not edit.",
        f"// `try_to_timestamp(text, pattern)` under LEGACY with the session zone UTC, Spark {fx['spark_version']}:",
        "// (text, pattern, epoch seconds or None for NULL).",
        "",
        "pub(crate) const PROBES: &[(&str, &str, Option<i64>)] = &[",
    ]
    for text, pattern, secs in fx["probes"]:
        probes.append(f"    ({lit(text)}, {lit(pattern)}, {'None' if secs is None else f'Some({secs})'}),")
    probes += ["];", ""]
    Path(args.probes).parent.mkdir(parents=True, exist_ok=True)
    Path(args.probes).write_text("\n".join(probes), encoding="utf-8")


if __name__ == "__main__":
    main()
