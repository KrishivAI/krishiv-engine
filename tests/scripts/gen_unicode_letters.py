#!/usr/bin/env python3
"""Generate the `\\p{L}` (Unicode letter) ranges of Spark's `UNICODE_LETTER` lexer fragment.

Spark's SQL lexer (`SqlBaseLexer.g4`) builds identifiers from `UNICODE_LETTER: [\\p{L}]`, ASCII digits
and `_`. Rust's `char::is_alphabetic` is the wider `Alphabetic` property (it adds letter numbers and
combining marks), so `krishiv-sql` uses this table instead. The ranges come from Python's
`unicodedata` (general category `L*`); the Unicode version is recorded in the output.

Usage (from repo root):

    python3 tests/scripts/gen_unicode_letters.py --out crates/krishiv-sql/src/generated/letters.rs
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path


def ranges() -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for cp in range(sys.maxunicode + 1):
        if unicodedata.category(chr(cp)).startswith("L"):
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="crates/krishiv-sql/src/generated/letters.rs")
    args = ap.parse_args()
    rows = "\n".join(f"    (0x{a:05X}, 0x{b:05X})," for a, b in ranges())
    text = (
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// @generated by tests/scripts/gen_unicode_letters.py; do not edit.\n"
        f"//! The `\\p{{L}}` ranges (Unicode {unicodedata.unidata_version}) of Spark's `UNICODE_LETTER`.\n\n"
        "/// Inclusive code point ranges of the Unicode letters, sorted.\n"
        f"pub(crate) const LETTERS: &[(u32, u32)] = &[\n{rows}\n];\n"
    )
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"wrote {len(ranges())} ranges (Unicode {unicodedata.unidata_version}) -> {args.out}")


if __name__ == "__main__":
    main()
