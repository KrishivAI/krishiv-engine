#!/usr/bin/env python3
"""Generate the table of Spark's `spark.sql.legacy.*` settings (P3 PR-05, ADR 0008).

Nothing is transcribed: for each Spark release a one-off throw-away container (images pinned by digest below)
runs `spark-shell` with `legacy_settings.scala`, which lists every registered SQL config entry whose key starts
with `spark.sql.legacy.` (internal ones included: `SQLConf.getConfigEntries` is `private[spark]`, so the script
calls it by reflection) with its default. The union over the releases is written to
`crates/krishiv-common/src/config/legacy_table.rs`: key, the distinct defaults, and the first release that
has it. `Config::set` uses it (`config/legacy.rs`): a `spark.sql.legacy.*` setting Krishiv does not honour is
accepted at a default and refused at any other value.

Usage (from the repo root; needs docker; about a minute per release):

    python3 tests/scripts/gen_legacy_settings.py

Output is deterministic.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCALA = Path(__file__).resolve().parent / "legacy_settings.scala"
OUT = ROOT / "crates/krishiv-common/src/config/legacy_table.rs"

# Releases whose registry is read, oldest first: version -> image pinned by digest.
IMAGES = {
    "3.5.9": "apache/spark:3.5.9@sha256:af02a459c8706e031c835c16f9db3c463816776e2543dd0f828af65606bcf392",
    "4.0.5": "apache/spark:4.0.5@sha256:45eb1b8261a89bc7692be05aa4664676856f1c886cecc7b97b4e10f635b45b3c",
    "4.1.4": "apache/spark:4.1.4@sha256:847f91f8bb2f28d632064dfe632d423020f8fd60b27c7704c0e5bf5b0c6432c7",
    "4.2.1": "apache/spark:4.2.1@sha256:0cb70cf0193ec81c93c6c47078208512bbe659dd9dc89535dd2773826f0ea2bf",
    "4.3.0": "apache/spark:4.3.0@sha256:3dedc5c8665a6f472e2f0a3a828207a79a30785090ef325d3af219cb90a73d63",
}
PREFIX = "spark.sql.legacy."
DEFAULT_RELEASE = "4.2.1"  # the default Spark profile (4.2)


def read_release(version: str, image: str) -> dict[str, str]:
    """key -> default, for one release. The script goes in by `-I FILE` (3.5) or on stdin (4.x: `-I` runs
    silently there); the first way that prints a registry wins."""
    base = ["docker", "run", "--rm", "-i", "--entrypoint", "", "-e", "HOME=/tmp"]
    shell = ["/opt/spark/bin/spark-shell", "--master", "local[1]"]
    ways = [
        (
            [*base, "-v", f"{SCALA}:/tmp/legacy_settings.scala:ro", image, *shell, "-I", "/tmp/legacy_settings.scala"],
            "",
        ),
        ([*base, image, *shell], SCALA.read_text(encoding="utf-8")),
    ]
    stderr = ""
    for cmd, stdin in [w for w in ways for _ in range(2)]:  # each way twice: a cold container can stall
        done = subprocess.run(cmd, input=stdin, capture_output=True, text=True, check=False, timeout=900)
        stderr = done.stderr
        # the REPL echoes a prompt before the last line (`scala> @@END`)
        lines = [ln[ln.index("@@") :] for ln in done.stdout.splitlines() if "@@" in ln]
        if "@@END" in lines and any(ln.startswith("@@L\t") for ln in lines):
            out = {}
            for ln in lines:
                if ln.startswith("@@L\t"):
                    _, key, default = ln.split("\t")[:3]
                    out[key] = default
            return out
    raise SystemExit(f"Spark {version}: no registry printed:\n{stderr[-1500:]}")


def rust_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    per_release = {}
    for version, image in IMAGES.items():
        per_release[version] = read_release(version, image)
        print(f"Spark {version}: {len(per_release[version])} legacy settings", file=sys.stderr)
    keys = sorted({k for r in per_release.values() for k in r})
    rows = []
    for key in keys:
        assert key.startswith(PREFIX), key
        defaults = []
        first = ""
        for version, reg in per_release.items():
            if key in reg:
                first = first or version
                if reg[key] not in defaults:
                    defaults.append(reg[key])
        rows.append((key, defaults, first, per_release[DEFAULT_RELEASE].get(key, "")))
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// @generated by tests/scripts/gen_legacy_settings.py from the Spark releases "
        + ", ".join(IMAGES)
        + ". Do not edit.",
        "",
        "/// Every `spark.sql.legacy.*` setting any supported Spark release registers: the key, the defaults it has",
        "/// across the releases (as Spark prints them, `<undefined>` for none), the first release that has it,",
        "/// and its default in the default profile's release (empty when that release does not register it).",
        "pub(super) const SPARK_LEGACY_SETTINGS: &[(&str, &[&str], &str, &str)] = &[",
    ]
    for key, defaults, first, current in rows:
        ds = ", ".join(rust_str(d) for d in defaults)
        out.append(f"    ({rust_str(key)}, &[{ds}], {rust_str(first)}, {rust_str(current)}),")
    out.append("];")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(rows)} settings -> {OUT.relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
