"""Per-version summary (the committed dashboard input) and the Markdown dashboard."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from .denominator import Denominator
from .junit import Record

# Files whose tests never contact a server (design §2; confirm at the first run).
CLIENT_ONLY_FILES = (
    "test_connect_plan.py",
    "test_connect_channel.py",
    "client/test_client.py",
    "client/test_client_retries.py",
)


def summarize(den: Denominator, remaining: set[str], records: list[Record], *, source: str) -> dict:
    """`source` is `static` (ast census, nothing run) or `collected` (pytest) / `run`."""
    status = {r.test_id: r.status for r in records if r.test_id in remaining}
    passed = {t for t, s in status.items() if s == "pass"}
    # A whole-file timeout, crash or missing XML is a `<file>` record; keep it visible, not just in `not_run`.
    file_failures = sorted({r.file for r in records if r.test == "<file>"})
    client_only = {t for t in remaining if t.split("::", 1)[0] in CLIENT_ONLY_FILES}

    def rate(num: int, dnm: int) -> float:
        return round(100 * num / dnm, 2) if dnm else 0.0

    server_den = len(remaining) - len(client_only)
    return {
        "version": den.version,
        "source": source,
        "denominator": den.as_dict(),
        "counts": dict(sorted(Counter(status.values()).items())),
        "not_run": len(remaining) - len(status),
        "file_failures": file_failures,
        "passed": len(passed),
        "pass_rate": rate(len(passed), den.denominator),
        "client_only": len(client_only),
        "pass_rate_without_client_only": rate(len(passed - client_only), server_den),
        "passed_ids": sorted(passed),  # the pass-list ratchet input
    }


def write_summary(summary: dict, out_dir: Path) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{summary['version']}.json"
    path.write_text(json.dumps(summary, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return path


def ratchet_regressions(previous: dict, current: dict) -> list[str]:
    """Ids that passed before and do not now: the CI failure list."""
    return sorted(set(previous.get("passed_ids", [])) - set(current["passed_ids"]))


def dashboard(summaries: list[dict]) -> str:
    lines = [
        "# PySpark Connect pass rate",
        "",
        "Generated by `tests/scripts/pyspark_suite` (P3-T030); do not edit. Denominator parts follow",
        "`design/P3-pyspark-suite-runner.md` §2. `static` rows are an `ast` census, not a collected run.",
        "",
        "| Spark | source | collected | Spark skips | oracle env | manifest | denominator | passed | pass rate "
        "| without client-only | excluded share (cap 20%) |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for s in sorted(summaries, key=lambda x: x["version"], reverse=True):
        d = s["denominator"]
        lines.append(
            f"| {s['version']} | {s['source']} | {d['collected']} | {d['spark_skips']} | {d['oracle_env']} | "
            f"{d['manifest']} | {d['denominator']} | {s['passed']} | {s['pass_rate']}% | "
            f"{s['pass_rate_without_client_only']}% | {100 * d['excluded_share']:.1f}%"
            f"{'' if d['within_cap'] else ' **OVER CAP**'} |"
        )
    lines += ["", "Excluded tests by reason class:", ""]
    for s in sorted(summaries, key=lambda x: x["version"], reverse=True):
        parts = ", ".join(f"{k} {v}" for k, v in s["denominator"]["by_reason"].items()) or "none"
        lines.append(f"- {s['version']}: {parts}")
    return "\n".join(lines) + "\n"
