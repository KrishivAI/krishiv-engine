"""Write the Python API reference as Markdown into `docs/reference/python/`.

Reads the sources of `python/krishiv` with the standard library's `ast` (nothing is imported, so the
compiled extension is not needed and no third-party generator is added; ADR 0028). One page per public
module and an index. `krishiv.sql.functions` also lists the generated wrappers of
`_generated_functions.py`.

Usage:  python3 -I tests/scripts/gen_python_docs.py [--check]
"""

from __future__ import annotations

import ast
import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PKG = ROOT / "python" / "krishiv"
OUT = ROOT / "docs" / "reference" / "python"
MERGED = {"krishiv.sql.functions": ["krishiv/sql/_generated_functions.py"]}
HEADER = "<!-- @generated by `python3 tests/scripts/gen_python_docs.py`; do not edit. -->"


def modules() -> list[tuple[str, Path]]:
    out = []
    for path in sorted(PKG.rglob("*.py")):
        rel = path.relative_to(PKG.parent).with_suffix("")
        parts = list(rel.parts)
        if parts[-1] == "__init__":
            parts.pop()
        if any(p.startswith("_") for p in parts[1:]):
            continue
        out.append((".".join(parts), path))
    return out


def md_doc(doc: str | None) -> str:
    if not doc:
        return ""
    text = re.sub(r"``([^`]+)``", r"`\1`", inspect.cleandoc(doc))
    lines = text.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        nxt = lines[i + 1] if i + 1 < len(lines) else ""
        if line.strip() and nxt.strip() and set(nxt.strip()) == {"-"} and len(nxt.strip()) >= 3:
            out += [f"**{line.strip()}**", ""]  # a numpydoc section title, not a setext heading
            i += 2
            continue
        if line.lstrip().startswith(">>>"):
            out.append("```python")
            while i < len(lines) and lines[i].strip():
                out.append(lines[i])
                i += 1
            out.append("```")
            continue
        out.append(line)
        i += 1
    return "\n".join(out)


def is_public(name: str, exported: set[str] | None) -> bool:
    if exported is not None:
        return name in exported
    return not name.startswith("_")


def exports(tree: ast.Module) -> set[str] | None:
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets):
            try:
                return {str(x) for x in ast.literal_eval(node.value)}
            except ValueError:
                return None
    return None


def signature(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    args = ast.unparse(fn.args)
    ret = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""
    prefix = "async def" if isinstance(fn, ast.AsyncFunctionDef) else "def"
    return f"{prefix} {fn.name}({args}){ret}"


def decorators(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> list[str]:
    return [ast.unparse(d) for d in fn.decorator_list]


def is_overload(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    return any(d.endswith("overload") for d in decorators(fn))


def render_function(fn: ast.FunctionDef | ast.AsyncFunctionDef, level: int) -> str:
    deco = [d for d in decorators(fn) if d in ("property", "staticmethod", "classmethod") or d.endswith(".setter")]
    lines = [f"{'#' * level} `{fn.name}`", "", "```python"]
    lines += [f"@{d}" for d in deco]
    lines += [signature(fn), "```", ""]
    doc = md_doc(ast.get_docstring(fn))
    if doc:
        lines += [doc, ""]
    return "\n".join(lines)


def functions_of(body: list[ast.stmt], exported: set[str] | None) -> list[ast.FunctionDef | ast.AsyncFunctionDef]:
    seen: dict[str, ast.FunctionDef | ast.AsyncFunctionDef] = {}
    for node in body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and is_public(node.name, exported):
            if is_overload(node) and node.name in seen:
                continue
            if any(d.endswith(".setter") for d in decorators(node)):
                continue
            seen[node.name] = node
    return sorted(seen.values(), key=lambda f: f.name)


def render_class(cls: ast.ClassDef) -> str:
    bases = ", ".join(ast.unparse(b) for b in cls.bases)
    lines = [
        f"## `{cls.name}`",
        "",
        "```python",
        f"class {cls.name}({bases})" if bases else f"class {cls.name}",
        "```",
        "",
    ]
    doc = md_doc(ast.get_docstring(cls))
    if doc:
        lines += [doc, ""]
    for fn in functions_of(cls.body, None):
        if fn.name.startswith("__") and fn.name != "__init__":
            continue
        if fn.name == "__init__" and not ast.get_docstring(fn):
            continue
        lines.append(render_function(fn, 3))
    return "\n".join(lines)


def render_module(name: str, path: Path) -> str:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    exported = exports(tree)
    body = list(tree.body)
    for extra in MERGED.get(name, []):
        sub = ast.parse((PKG.parent / extra).read_text(encoding="utf-8"))
        body += sub.body
        if exported is not None:
            exported |= exports(sub) or set()
    lines = [f"# `{name}`", "", HEADER, ""]
    doc = md_doc(ast.get_docstring(tree))
    if doc:
        lines += [doc, ""]
    classes = sorted(
        (n for n in body if isinstance(n, ast.ClassDef) and is_public(n.name, exported)), key=lambda c: c.name
    )
    funcs = functions_of(body, exported)
    if funcs:
        lines += ["## Functions", ""]
        lines += [render_function(f, 3) for f in funcs]
    lines += [render_class(c) for c in classes]
    return "\n".join(lines).rstrip() + "\n"


def render() -> dict[Path, str]:
    pages: dict[Path, str] = {}
    index = ["# Python API reference", "", HEADER, "", "| Module | Summary |", "|---|---|"]
    for name, path in modules():
        tree = ast.parse(path.read_text(encoding="utf-8"))
        summary = (ast.get_docstring(tree) or "").strip().splitlines()[:1]
        pages[OUT / f"{name}.md"] = render_module(name, path)
        index.append(f"| [`{name}`]({name}.md) | {summary[0].replace('|', chr(92) + '|') if summary else ''} |")
    pages[OUT / "index.md"] = "\n".join(index) + "\n"
    pages[OUT / "_meta.json"] = '{\n  "index": "Python API"\n}\n'
    return pages


def main(argv: list[str]) -> int:
    pages = render()
    if "--check" in argv:
        have = {p for p in OUT.glob("*.[mj]*")} if OUT.is_dir() else set()
        bad = [
            str(p.relative_to(ROOT)) for p, t in pages.items() if not p.exists() or p.read_text(encoding="utf-8") != t
        ]
        bad += [f"{p.relative_to(ROOT)} (extra)" for p in sorted(have - set(pages))]
        if bad:
            print(f"docs/reference/python is stale ({len(bad)} files, first: {bad[0]}); run `cargo xtask docs-python`")
            return 1
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in set(OUT.glob("*.[mj]*")) - set(pages):
        stale.unlink()
    for path, text in pages.items():
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(pages)} pages to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
