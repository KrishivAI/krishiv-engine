//! Generates the `krishiv.access.v1` Rust code from `proto/krishiv/access/v1/access.proto`
//! (ADR 0049 §3).
//!
//! ```text
//! cargo run --locked --manifest-path tools/access-protogen/Cargo.toml -- --write
//! cargo run --locked --manifest-path tools/access-protogen/Cargo.toml -- --check
//! ```
//!
//! Run it from the repository root. Two files come out:
//!
//! - `crates/krishiv-access-proto/src/access.v1.pb.rs`: the `prost` messages, with no transport,
//!   for any crate that speaks the protocol;
//! - `crates/krishiv-server/src/access_external/access.v1.grpc.rs`: the `tonic` client and server
//!   of `AccessPolicy` over those messages (the server side is what an adapter, or a test service,
//!   implements).
//!
//! `--check` regenerates in memory and fails when a file on disk differs. The compiler is
//! `protox`: no `protoc` is needed on any machine.

use std::path::Path;
use std::process::ExitCode;

const PROTO_DIR: &str = "proto";
const PROTO: &str = "krishiv/access/v1/access.proto";
const MESSAGES: &str = "crates/krishiv-access-proto/src/access.v1.pb.rs";
const GRPC: &str = "crates/krishiv-server/src/access_external/access.v1.grpc.rs";

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("access-protogen: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<()> {
    let mode = std::env::args().nth(1).unwrap_or_default();
    if mode != "--write" && mode != "--check" {
        return Err("pass --write or --check".into());
    }
    let fds = protox::compile([PROTO], [PROTO_DIR])?;
    let scratch = std::env::temp_dir().join(format!("access-protogen-{}", std::process::id()));

    // The messages alone.
    let messages = scratch.join("messages");
    std::fs::create_dir_all(&messages)?;
    let mut config = prost_build::Config::new();
    config.btree_map(["."]);
    config.out_dir(&messages);
    config.compile_fds(fds.clone())?;
    let message_code = std::fs::read_to_string(messages.join("krishiv.access.v1.rs"))?;

    // The services over the messages of `krishiv_access_proto`.
    let grpc = scratch.join("grpc");
    std::fs::create_dir_all(&grpc)?;
    let mut config = prost_build::Config::new();
    config.btree_map(["."]);
    config.extern_path(".krishiv.access.v1", "::krishiv_access_proto");
    config.out_dir(&grpc);
    tonic_prost_build::configure()
        .build_client(true)
        .build_server(true)
        .build_transport(false)
        .out_dir(&grpc)
        .compile_fds_with_config(fds, config)?;
    let grpc_code = std::fs::read_to_string(grpc.join("krishiv.access.v1.rs"))?;
    std::fs::remove_dir_all(&scratch)?;

    let header = "// SPDX-License-Identifier: Apache-2.0\n// @generated by tools/access-protogen; do not edit.\n";
    write_or_check(&mode, MESSAGES, format!("{header}{message_code}"))?;
    write_or_check(&mode, GRPC, format!("{header}{grpc_code}"))
}

fn write_or_check(mode: &str, path: &str, text: String) -> Result<()> {
    let path = Path::new(path);
    if mode == "--write" {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        std::fs::write(path, text)?;
    } else if std::fs::read_to_string(path).ok().as_deref() != Some(text.as_str()) {
        return Err(format!("{} is out of date; run the generator with --write", path.display()).into());
    }
    Ok(())
}
