//! Generates `crates/krishiv-plan-codec/src/proto/krishiv.plan.v1.pb.rs` from
//! `proto/krishiv/plan/v1/plan.proto`.
//!
//! ```text
//! cargo run --locked --manifest-path tools/plan-protogen/Cargo.toml -- --write
//! cargo run --locked --manifest-path tools/plan-protogen/Cargo.toml -- --check
//! ```
//!
//! Run it from the repository root. `--check` regenerates in memory and
//! fails when the file on disk differs, so CI notices a proto change without
//! a regeneration. The compiler is `protox`: no `protoc` is needed.

use std::path::Path;

use prost_build::Module;
use std::process::ExitCode;

const PROTO_DIR: &str = "proto";
const PROTO: &str = "krishiv/plan/v1/plan.proto";
const OUTPUT: &str = "crates/krishiv-plan-codec/src/proto/krishiv.plan.v1.pb.rs";

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("plan-protogen: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<()> {
    let mode = std::env::args().nth(1).unwrap_or_default();
    if mode != "--write" && mode != "--check" {
        return Err("pass --write or --check".into());
    }
    let fds = protox::compile([PROTO], [PROTO_DIR])?;
    let mut config = prost_build::Config::new();
    // Deterministic iteration order for map fields (read options).
    config.btree_map(["."]);
    let requests: Vec<_> = fds
        .file
        .iter()
        .map(|f| (Module::from_protobuf_package_name(f.package()), f.clone()))
        .collect();
    let code = config
        .generate(requests)?
        .into_iter()
        .find_map(|(module, code)| module.parts().eq(["krishiv", "plan", "v1"]).then_some(code))
        .ok_or("the package krishiv.plan.v1 was not generated")?;
    let bytes = format!("// SPDX-License-Identifier: Apache-2.0\n// @generated by tools/plan-protogen; do not edit.\n{code}").into_bytes();
    let path = Path::new(OUTPUT);
    if mode == "--write" {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir)?;
        }
        std::fs::write(path, bytes)?;
    } else if std::fs::read(path).ok().as_deref() != Some(bytes.as_slice()) {
        return Err(format!("{OUTPUT} is out of date; run the generator with --write").into());
    }
    Ok(())
}
