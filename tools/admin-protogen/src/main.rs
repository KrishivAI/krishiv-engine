//! Generates the `krishiv.admin.v1` Rust code from `proto/krishiv/admin/v1/admin.proto`.
//!
//! ```text
//! cargo run --locked --manifest-path tools/admin-protogen/Cargo.toml -- --write
//! cargo run --locked --manifest-path tools/admin-protogen/Cargo.toml -- --check
//! ```
//!
//! Run it from the repository root. Two files come out under `crates/krishiv-server/src/admin_v1/`:
//!
//! - `admin.v1.pb.rs`: the `prost` messages and the `tonic` server side of `AdminService`;
//! - `descriptor.bin`: the encoded descriptor set (with the imports), which the server reads with
//!   `prost-reflect` to produce and parse the REST JSON and to build the route table.
//!
//! `--check` regenerates in memory and fails when a file on disk differs. The compiler is
//! `protox`: no `protoc` is needed on any machine.

use std::path::Path;
use std::process::ExitCode;

use prost::Message;

const PROTO_DIR: &str = "proto";
const PROTO: &str = "krishiv/admin/v1/admin.proto";
const OUT_DIR: &str = "crates/krishiv-server/src/admin_v1";

type Result<T> = std::result::Result<T, Box<dyn std::error::Error>>;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("admin-protogen: {e}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<()> {
    let mode = std::env::args().nth(1).unwrap_or_default();
    if mode != "--write" && mode != "--check" {
        return Err("pass --write or --check".into());
    }
    let fds = protox::compile([PROTO], [PROTO_DIR])?;
    // A fresh private directory (not a predictable name under the shared temp dir), removed on drop.
    let scratch_dir = tempfile::tempdir()?;
    let scratch = scratch_dir.path();
    let mut config = prost_build::Config::new();
    // Deterministic iteration order for map fields.
    config.btree_map(["."]);
    config.out_dir(&scratch);
    tonic_prost_build::configure()
        .build_client(false)
        .build_server(true)
        .out_dir(&scratch)
        .compile_fds_with_config(fds.clone(), config)?;
    let code = std::fs::read_to_string(scratch.join("krishiv.admin.v1.rs"))?;
    scratch_dir.close()?;
    let rust = format!(
        "// SPDX-License-Identifier: Apache-2.0\n// @generated by tools/admin-protogen; do not edit.\n{code}"
    )
    .into_bytes();
    write_or_check(&mode, "admin.v1.pb.rs", rust)?;
    write_or_check(&mode, "descriptor.bin", fds.encode_to_vec())
}

fn write_or_check(mode: &str, name: &str, bytes: Vec<u8>) -> Result<()> {
    let path = Path::new(OUT_DIR).join(name);
    if mode == "--write" {
        std::fs::create_dir_all(OUT_DIR)?;
        std::fs::write(&path, bytes)?;
    } else if std::fs::read(&path).ok().as_deref() != Some(bytes.as_slice()) {
        return Err(format!("{} is out of date; run the generator with --write", path.display()).into());
    }
    Ok(())
}
