//! The checked-in error-class reference is what `cargo xtask docs-errors` generates.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use krishiv_common::error::{Audience, ErrorClass};
use xtask::docs_errors::{OUT_DIR, render, run};

#[expect(
    clippy::unwrap_used,
    reason = "a test helper: the manifest directory has a parent"
)]
fn root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap()
}

fn page(pages: &BTreeMap<PathBuf, String>, file: &str) -> String {
    pages[&Path::new(OUT_DIR).join(file)].clone()
}

#[test]
fn the_checked_in_error_pages_match_the_generator() {
    run(root(), true).unwrap();
}

#[test]
fn every_class_has_one_heading_on_one_page() {
    let pages = render();
    let mut headings: BTreeMap<&str, usize> = BTreeMap::new();
    for (path, text) in &pages {
        if path.ends_with("index.md") {
            continue;
        }
        for line in text.lines() {
            if let Some(name) = line.strip_prefix("## ") {
                *headings.entry(name).or_default() += 1;
            }
        }
    }
    for class in ErrorClass::ALL {
        assert_eq!(headings.get(class.name()), Some(&1), "{}", class.name());
    }
    assert_eq!(headings.len(), ErrorClass::ALL.len());
}

#[test]
fn classes_are_grouped_by_origin_and_first_letter() {
    let pages = render();
    assert!(page(&pages, "d.md").contains("\n## DIVIDE_BY_ZERO\n"));
    assert!(page(&pages, "delta.md").contains("\n## DELTA_"));
    assert!(!page(&pages, "d.md").contains("\n## DELTA_"));
    assert!(page(&pages, "krishiv.md").contains("\n## KRISHIV_UNSUPPORTED_FEATURE\n"));
    assert!(!page(&pages, "k.md").contains("\n## KRISHIV_"));
    assert!(page(&pages, "legacy.md").contains("\n## _LEGACY_ERROR_TEMP_"));
}

#[test]
fn a_class_shows_its_sqlstate_and_template_verbatim() {
    let pages = render();
    let d = page(&pages, "d.md");
    let section = d.split("\n## DIVIDE_BY_ZERO\n").nth(1).unwrap();
    let section = section.split("\n## ").next().unwrap();
    assert!(section.starts_with("\nSQLSTATE `22012`.\n"), "{section}");
    let class = ErrorClass::ALL
        .iter()
        .find(|c| c.name() == "DIVIDE_BY_ZERO")
        .unwrap();
    // Inside a fenced block `<config>` stays as it is: no HTML escaping.
    assert!(
        section.contains(&format!(
            "\n~~~text\n{}\n~~~\n",
            class.message_template().trim_end()
        )),
        "{section}"
    );
}

#[test]
fn a_class_without_a_sqlstate_and_an_operator_class_say_so() {
    let pages = render();
    let all: String = pages.values().map(String::as_str).collect();
    let section = |name: &str| {
        let from = all.split(&format!("\n## {name}\n")).nth(1).unwrap();
        from.split("\n~~~text\n").next().unwrap().to_owned()
    };
    let stateless = ErrorClass::ALL
        .iter()
        .find(|c| c.sql_state().is_none())
        .unwrap();
    assert!(section(stateless.name()).contains("No SQLSTATE."));
    let operator = ErrorClass::ALL
        .iter()
        .find(|c| c.audience() == Audience::Operator)
        .unwrap();
    assert!(section(operator.name()).contains("Only operators see"));
    let user = ErrorClass::ALL
        .iter()
        .find(|c| c.audience() == Audience::User)
        .unwrap();
    assert!(!section(user.name()).contains("Only operators see"));
}

#[test]
fn no_template_can_end_its_fenced_block_early() {
    for class in ErrorClass::ALL {
        assert!(
            !class
                .message_template()
                .lines()
                .any(|l| l.trim_start().starts_with("~~~")),
            "{}",
            class.name()
        );
    }
}

#[test]
fn the_index_links_every_page_and_names_no_class() {
    let pages = render();
    let index = page(&pages, "index.md");
    for path in pages.keys() {
        let file = path.file_name().unwrap().to_str().unwrap();
        if file != "index.md" {
            assert!(index.contains(&format!("]({file})")), "{file}");
        }
    }
    // A new class must not change the index: every branch that adds one would edit it.
    // (`DIVIDE_BY_ZERO` appears once, in the sentence that shows what an error looks like.)
    for class in ["ARITHMETIC_OVERFLOW", "KRISHIV_UNSUPPORTED_FEATURE"] {
        assert!(!index.contains(class), "{class}");
    }
}

#[test]
fn every_page_has_a_description_and_the_generated_comment() {
    for (path, text) in render() {
        assert!(
            text.starts_with("---\ndescription: \""),
            "{}",
            path.display()
        );
        assert!(
            text.contains("<!-- @generated by `cargo xtask docs-errors`; do not edit. -->"),
            "{}",
            path.display()
        );
        assert!(
            text.ends_with('\n') && !text.ends_with("\n\n"),
            "{}",
            path.display()
        );
    }
}

#[test]
fn check_reports_missing_stale_and_extra_pages_and_a_write_removes_them() {
    let dir = tempfile::tempdir().unwrap();
    let out = dir.path().join(OUT_DIR);
    let missing = run(dir.path(), true).unwrap_err();
    assert!(missing.contains("cargo xtask docs-errors"), "{missing}");
    run(dir.path(), false).unwrap();
    run(dir.path(), true).unwrap();
    // `_meta.json` is hand-written: neither a check nor a write touches it.
    std::fs::write(out.join("_meta.json"), "{}\n").unwrap();
    std::fs::write(out.join("gone.md"), "old\n").unwrap();
    let extra = run(dir.path(), true).unwrap_err();
    assert!(extra.contains("gone.md (extra)"), "{extra}");
    std::fs::write(out.join("d.md"), "edited\n").unwrap();
    run(dir.path(), false).unwrap();
    assert!(!out.join("gone.md").exists());
    assert!(out.join("_meta.json").exists());
    run(dir.path(), true).unwrap();
}
