//! `cargo xtask docs-errors [--check]`: the error-class reference, one page per first letter of
//! Spark's class names plus one each for the Delta Lake, Krishiv and legacy classes, generated into
//! `docs/reference/errors/` from the krishiv-common registry.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use krishiv_common::error::{Audience, ErrorClass};

/// The directory of the generated pages, relative to the repository root.
pub const OUT_DIR: &str = "docs/reference/errors";

const GENERATED: &str = "<!-- @generated by `cargo xtask docs-errors`; do not edit. -->";

/// The pages that are not a letter of Spark's classes: file stem, title, class-name prefix.
const NAMED: &[(&str, &str, &str)] = &[
    ("delta", "Delta Lake error classes", "DELTA_"),
    ("krishiv", "Krishiv error classes", "KRISHIV_"),
    ("legacy", "Spark legacy error classes", "_"),
];

/// The file stem of the page that lists `name`.
fn stem(name: &str) -> String {
    NAMED
        .iter()
        .find(|(_, _, prefix)| name.starts_with(prefix))
        .map_or_else(
            || {
                name.chars()
                    .take(1)
                    .collect::<String>()
                    .to_ascii_lowercase()
            },
            |(stem, _, _)| (*stem).to_owned(),
        )
}

/// A page's front matter, title and generated comment.
fn head(title: &str, description: &str) -> String {
    format!("---\ndescription: \"{description}\"\n---\n\n# {title}\n\n{GENERATED}\n")
}

/// One class: its name as the heading (the page anchor), its SQLSTATE and its message template.
/// The template is in a fenced block, so `<parameter>` and `|` need no escaping.
fn section(out: &mut String, class: ErrorClass) {
    let state = class
        .sql_state()
        .map_or_else(|| "No SQLSTATE.".to_owned(), |s| format!("SQLSTATE `{s}`."));
    let audience = match class.audience() {
        Audience::User => "",
        Audience::Operator => {
            " Only operators see its details: a server sends a client the message with its values replaced."
        }
    };
    // Writing to a `String` cannot fail.
    let _ = write!(
        out,
        "\n## {}\n\n{state}{audience}\n\n~~~text\n{}\n~~~\n",
        class.name(),
        class.message_template().trim_end()
    );
}

/// The index: links to the pages. It names no class, so adding one leaves it unchanged.
fn index(stems: &[&String]) -> String {
    let mut out = head(
        "Error classes",
        "Every error class of Krishiv's registry, with its SQLSTATE and message.",
    );
    out.push_str(
        "\nAn error names its class first, as in Spark: `[DIVIDE_BY_ZERO] ...`, then its SQLSTATE. Each entry shows\n\
         the message template; a `<name>` in it is filled in when the error is raised.\n\n\
         The registry holds the classes of Apache Spark 4.2.1 and 4.3.0 (a class in both shows the 4.2.1 text),\n\
         the Delta Lake classes Krishiv uses and Krishiv's own. A class listed here is not necessarily one\n\
         Krishiv raises.\n\n\
         ## Spark classes, by first letter\n\n",
    );
    for letter in stems.iter().filter(|s| s.len() == 1) {
        let _ = writeln!(out, "- [{}]({letter}.md)", letter.to_ascii_uppercase());
    }
    out.push_str("\n## Other classes\n\n");
    for (stem, title, prefix) in NAMED {
        if stems.iter().any(|s| s.as_str() == *stem) {
            let _ = writeln!(out, "- [{title}]({stem}.md): names starting `{prefix}`");
        }
    }
    out
}

/// Every page of the reference, by path relative to the repository root.
#[must_use]
pub fn render() -> BTreeMap<PathBuf, String> {
    let mut groups: BTreeMap<String, Vec<ErrorClass>> = BTreeMap::new();
    for &class in ErrorClass::ALL {
        groups.entry(stem(class.name())).or_default().push(class);
    }
    let dir = Path::new(OUT_DIR);
    let mut pages = BTreeMap::new();
    pages.insert(
        dir.join("index.md"),
        index(&groups.keys().collect::<Vec<_>>()),
    );
    for (stem, classes) in &groups {
        let (title, description) = match NAMED.iter().find(|(s, _, _)| s == stem) {
            Some((_, title, prefix)) => (
                (*title).to_owned(),
                format!("{title} (names starting {prefix}): SQLSTATE and message of each."),
            ),
            None => {
                let letter = stem.to_ascii_uppercase();
                (
                    format!("Error classes: {letter}"),
                    format!(
                        "Spark error classes starting with {letter}: SQLSTATE and message of each."
                    ),
                )
            }
        };
        let mut page = head(&title, &description);
        page.push_str("\n[All error class pages](index.md)\n");
        for &class in classes {
            section(&mut page, class);
        }
        pages.insert(dir.join(format!("{stem}.md")), page);
    }
    pages
}

/// Writes the pages (removing stale ones), or with `check` compares them with the files on disk.
/// Only `.md` files are touched; the directory's `_meta.json` is hand-written.
///
/// # Errors
/// On I/O errors, or with `check` when a page is missing, stale or extra.
pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let want = render();
    let dir = root.join(OUT_DIR);
    let mut have: Vec<PathBuf> = Vec::new();
    if dir.is_dir() {
        for entry in std::fs::read_dir(&dir).map_err(|e| format!("{}: {e}", dir.display()))? {
            let path = entry.map_err(|e| e.to_string())?.path();
            if path.extension().is_some_and(|x| x == "md") {
                have.push(Path::new(OUT_DIR).join(path.file_name().unwrap_or_default()));
            }
        }
    }
    let extra = have.iter().filter(|p| !want.contains_key(*p));
    if check {
        let mut bad: Vec<String> = want
            .iter()
            .filter(|(path, text)| {
                std::fs::read_to_string(root.join(path)).ok().as_ref() != Some(*text)
            })
            .map(|(path, _)| path.display().to_string())
            .collect();
        bad.extend(extra.map(|p| format!("{} (extra)", p.display())));
        return match bad.first() {
            None => Ok(()),
            Some(first) => Err(format!(
                "{OUT_DIR} is stale ({} files, first: {first}); run `cargo xtask docs-errors`",
                bad.len()
            )),
        };
    }
    std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
    for path in extra {
        std::fs::remove_file(root.join(path)).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    for (path, text) in &want {
        std::fs::write(root.join(path), text).map_err(|e| format!("{}: {e}", path.display()))?;
    }
    Ok(())
}
