//! `cargo xtask connect-coverage [--check]` (P3-T012a, owner decision 7): runs the `krishiv-connect`
//! binary `connect-coverage-dump` (the rows of `krishiv_connect::coverage`) and writes
//! `docs/reference/connect/coverage.md` and `tests/connect/coverage.json`. `--check` fails when either
//! file differs, as `docs-config --check` does. The rows live in code (an exhaustive match per
//! `oneof`), so a new proto arm is a compile error there until it has a row.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

const MD: &str = "docs/reference/connect/coverage.md";
const JSON: &str = "tests/connect/coverage.json";

/// Runs the generator, or with `check` compares with the committed files.
pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let out = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .current_dir(root)
        .args([
            "run",
            "--quiet",
            "--locked",
            "-p",
            "krishiv-connect",
            "--bin",
            "connect-coverage-dump",
        ])
        .output()
        .map_err(|e| format!("cannot run the dump: {e}"))?;
    if !out.status.success() {
        return Err(format!(
            "connect-coverage-dump failed:\n{}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    let json = String::from_utf8(out.stdout).map_err(|e| e.to_string())?;
    let md = render(&json)?;
    if check {
        let mut stale = Vec::new();
        for (path, text) in [(MD, &md), (JSON, &json)] {
            if std::fs::read_to_string(root.join(path)).ok().as_deref() != Some(text) {
                stale.push(path);
            }
        }
        return if stale.is_empty() {
            Ok(())
        } else {
            Err(format!(
                "{} is stale; run `cargo xtask connect-coverage`",
                stale.join(", ")
            ))
        };
    }
    for (path, text) in [(MD, &md), (JSON, &json)] {
        let p = root.join(path);
        if let Some(dir) = p.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        }
        std::fs::write(&p, text).map_err(|e| format!("{}: {e}", p.display()))?;
    }
    Ok(())
}

fn cell(s: &str) -> String {
    s.replace('|', "\\|")
}

/// The Markdown table, one section per `oneof`, from the dump's JSON.
fn render(json: &str) -> Result<String, String> {
    let rows: Vec<serde_json::Value> = serde_json::from_str(json).map_err(|e| e.to_string())?;
    let mut by_oneof: BTreeMap<String, Vec<&serde_json::Value>> = BTreeMap::new();
    let mut order: Vec<String> = Vec::new();
    for r in &rows {
        let name = r["oneof"].as_str().unwrap_or_default().to_owned();
        if !by_oneof.contains_key(&name) {
            order.push(name.clone());
        }
        by_oneof.entry(name).or_default().push(r);
    }
    let mut out = String::from(
        "<!-- Generated by `cargo xtask connect-coverage`; do not edit. -->\n\
         # Spark Connect coverage\n\n\
         Every arm of the `oneof` fields the Connect translator dispatches on, for the vendored protocol \
         version (Spark 4.2). A row that is not `done` or `partial` answers \
         `CONNECT_INVALID_PLAN.INVALID_ONE_OF_FIELD_NOT_SUPPORTED` (SQLSTATE 56K00).\n",
    );
    for name in &order {
        let rs = &by_oneof[name];
        let count = |s: &str| rs.iter().filter(|r| r["status"] == s).count();
        let _ = write!(
            out,
            "\n## {name}\n\n{} arms: {} done, {} partial, {} missing, {} out of scope.\n\n\
             | # | Arm | Status | Refused fields | IR target | Task | Group |\n|---:|---|---|---|---|---|---:|\n",
            rs.len(),
            count("done"),
            count("partial"),
            count("missing"),
            count("out of scope"),
        );
        for r in rs {
            let _ = writeln!(
                out,
                "| {} | {} | {} | {} | {} | {} | {} |",
                r["number"],
                r["field"].as_str().unwrap_or_default(),
                r["status"].as_str().unwrap_or_default(),
                cell(r["refused"].as_str().unwrap_or_default()),
                cell(r["target"].as_str().unwrap_or_default()),
                r["task"].as_str().unwrap_or_default(),
                r["group"]
            );
        }
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::render;

    #[test]
    fn renders_a_section_per_oneof() {
        let json = r#"[{"oneof":"A.b","field":"x","number":1,"status":"done","refused":"","target":"T|U","task":"P","group":0},
                       {"oneof":"A.b","field":"y","number":2,"status":"missing","refused":"","target":"","task":"Q","group":1}]"#;
        let md = render(json).unwrap();
        assert!(md.contains("## A.b"));
        assert!(md.contains("2 arms: 1 done, 0 partial, 1 missing, 0 out of scope."));
        assert!(md.contains("T\\|U"));
    }
}
