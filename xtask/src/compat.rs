//! `cargo xtask docs-compat`: the compatibility page, rendered from a data file
//! (`docs/concepts/compatibility.toml`, one status per surface) and the golden report
//! (`target/golden-report.json`, the pass rates of the Spark golden suite).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use serde::Deserialize;

/// One row of the data file.
#[derive(Debug, Deserialize)]
struct Surface {
    group: String,
    name: String,
    status: String,
    #[serde(default)]
    note: String,
}

/// The data file.
#[derive(Debug, Deserialize)]
struct Data {
    surface: Vec<Surface>,
}

/// The statuses the page allows.
const STATUSES: [&str; 3] = ["supported", "partial", "not yet"];

/// Renders the page from the data file's text and the golden report's JSON text.
///
/// # Errors
/// Returns a message when either input does not parse, a status is not one of
/// `supported`, `partial` or `not yet`, or the report lacks a number.
pub fn render(data: &str, report: &str) -> Result<String, String> {
    let data: Data = toml::from_str(data).map_err(|e| format!("compatibility data: {e}"))?;
    let report: serde_json::Value =
        serde_json::from_str(report).map_err(|e| format!("golden report: {e}"))?;
    let mut groups: BTreeMap<&str, Vec<&Surface>> = BTreeMap::new();
    for s in &data.surface {
        if !STATUSES.contains(&s.status.as_str()) {
            return Err(format!(
                "{}: status `{}` is not one of {STATUSES:?}",
                s.name, s.status
            ));
        }
        groups.entry(&s.group).or_default().push(s);
    }
    let mut out = String::new();
    out.push_str("---\ndescription: \"Spark compatibility per surface: file formats, object stores, SQL and Spark Connect.\"\n---\n\n");
    out.push_str("<!-- SPDX-License-Identifier: Apache-2.0 -->\n");
    out.push_str(
        "<!-- Generated by `cargo xtask docs-compat`; edit docs/concepts/compatibility.toml. -->\n",
    );
    out.push_str("# Spark compatibility\n\n");
    out.push_str("Status per surface. Anything not listed here is unknown and not supported.\n\n");
    for (group, rows) in &groups {
        let _ = writeln!(
            out,
            "## {group}\n\n| Surface | Status | Notes |\n| --- | --- | --- |"
        );
        for s in rows {
            let _ = writeln!(out, "| {} | {} | {} |", s.name, s.status, s.note);
        }
        out.push('\n');
    }
    let tag = report["spark_tag"].as_str().ok_or("report: spark_tag")?;
    let totals = &report["totals"];
    let _ = write!(
        out,
        "## Spark golden suite\n\nMeasured against Apache Spark {tag}'s own SQL test files \
         ({} statements in {} files).\n\n| Check | Passed | Total | Rate |\n| --- | --- | --- | --- |\n",
        count(&totals["statements"])?,
        count(&totals["files_run"])?,
    );
    for (label, key) in [
        ("Parse", "parse"),
        ("Error class of negative cases", "negative"),
        ("Result rows", "result"),
    ] {
        let (passed, total) = (
            count(&totals[key]["passed"])?,
            count(&totals[key]["total"])?,
        );
        let _ = writeln!(
            out,
            "| {label} | {passed} | {total} | {} |",
            rate(passed, total)
        );
    }
    Ok(out)
}

fn count(v: &serde_json::Value) -> Result<u64, String> {
    v.as_u64()
        .ok_or_else(|| format!("report: expected a number, found {v}"))
}

fn rate(passed: u64, total: u64) -> String {
    if total == 0 {
        return "n/a".to_owned();
    }
    // Tenths of a percent, rounded down: a page never rounds a failure away.
    let tenths = passed * 1000 / total;
    format!("{}.{}%", tenths / 10, tenths % 10)
}

/// Runs the command: `docs-compat [--report FILE] [--data FILE] [PATH]`; the page
/// goes to `PATH` or, without one, to stdout.
///
/// # Errors
/// Returns a message for bad flags, unreadable files or invalid input.
pub fn run(root: &Path, flags: &[&str]) -> Result<(), String> {
    let mut report = root.join("target/golden-report.json");
    let mut data = root.join("docs/concepts/compatibility.toml");
    let mut dest: Option<PathBuf> = None;
    let mut it = flags.iter();
    while let Some(f) = it.next() {
        match *f {
            "--report" => report = PathBuf::from(it.next().ok_or("--report needs a file")?),
            "--data" => data = PathBuf::from(it.next().ok_or("--data needs a file")?),
            p if !p.starts_with("--") && dest.is_none() => dest = Some(PathBuf::from(p)),
            other => return Err(format!("docs-compat: unexpected `{other}`")),
        }
    }
    let read = |p: &Path| {
        std::fs::read_to_string(p).map_err(|e| format!("cannot read {}: {e}", p.display()))
    };
    let page = render(
        &read(&data)?,
        &read(&report).map_err(|e| {
            format!("{e} (run `cargo xtask golden --engine session` first, or pass --report)")
        })?,
    )?;
    crate::docs::emit(&page, dest.as_deref(), &mut std::io::stdout())
}

#[cfg(test)]
mod tests {
    use super::*;

    const REPORT: &str = r#"{"spark_tag":"v4.2.0","totals":{"files_run":2,"statements":10,
        "parse":{"passed":9,"total":10},"negative":{"passed":0,"total":0},
        "result":{"passed":1,"total":3}}}"#;
    const DATA: &str = r#"
[[surface]]
group = "File formats"
name = "Parquet"
status = "supported"
[[surface]]
group = "File formats"
name = "ORC"
status = "not yet"
note = "later"
"#;

    #[test]
    fn the_page_lists_surfaces_and_rates() -> Result<(), String> {
        let page = render(DATA, REPORT)?;
        assert!(page.contains("| Parquet | supported |  |"), "{page}");
        assert!(page.contains("| ORC | not yet | later |"), "{page}");
        assert!(page.contains("| Parse | 9 | 10 | 90.0% |"), "{page}");
        assert!(
            page.contains("| Error class of negative cases | 0 | 0 | n/a |"),
            "{page}"
        );
        assert!(page.contains("| Result rows | 1 | 3 | 33.3% |"), "{page}");
        assert!(page.contains("Apache Spark v4.2.0"), "{page}");
        Ok(())
    }

    #[test]
    fn an_unknown_status_is_refused() {
        let bad = DATA.replace("supported", "mostly");
        let err = render(&bad, REPORT).expect_err("refused");
        assert!(err.contains("mostly"), "{err}");
    }

    #[test]
    fn a_report_without_numbers_is_refused() {
        assert!(render(DATA, r#"{"spark_tag":"v4.2.0","totals":{}}"#).is_err());
    }

    #[test]
    fn rates_round_down() {
        assert_eq!(rate(999, 1000), "99.9%");
        assert_eq!(rate(1, 3), "33.3%");
        assert_eq!(rate(2, 3), "66.6%");
    }

    #[test]
    fn the_committed_data_file_is_valid() -> Result<(), String> {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let data = std::fs::read_to_string(root.join("docs/concepts/compatibility.toml"))
            .map_err(|e| e.to_string())?;
        render(&data, REPORT).map(|_| ())
    }

    fn scratch(name: &str) -> Result<PathBuf, String> {
        let dir = std::env::temp_dir().join(format!("xtask-compat-{}-{name}", std::process::id()));
        std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
        Ok(dir)
    }

    #[test]
    fn run_writes_the_page_to_a_file() -> Result<(), String> {
        let dir = scratch("write")?;
        let (data, report, page) = (dir.join("d.toml"), dir.join("r.json"), dir.join("out/p.md"));
        std::fs::write(&data, DATA).map_err(|e| e.to_string())?;
        std::fs::write(&report, REPORT).map_err(|e| e.to_string())?;
        let flags = [
            "--data",
            data.to_str().ok_or("path")?,
            "--report",
            report.to_str().ok_or("path")?,
            page.to_str().ok_or("path")?,
        ];
        run(&dir, &flags)?;
        let text = std::fs::read_to_string(&page).map_err(|e| e.to_string())?;
        assert!(text.contains("| Parse | 9 | 10 | 90.0% |"), "{text}");
        std::fs::remove_dir_all(&dir).map_err(|e| e.to_string())
    }

    #[test]
    fn run_names_the_fix_for_a_missing_report() -> Result<(), String> {
        let dir = scratch("missing")?;
        let data = dir.join("d.toml");
        std::fs::write(&data, DATA).map_err(|e| e.to_string())?;
        let err = run(&dir, &["--data", data.to_str().ok_or("path")?]).expect_err("no report");
        assert!(err.contains("cargo xtask golden --engine session"), "{err}");
        std::fs::remove_dir_all(&dir).map_err(|e| e.to_string())
    }

    #[test]
    fn run_refuses_bad_flags() {
        let root = Path::new(".");
        assert!(run(root, &["--bogus"]).is_err());
        assert!(run(root, &["--report"]).is_err());
        assert!(run(root, &["--data"]).is_err());
    }
}
