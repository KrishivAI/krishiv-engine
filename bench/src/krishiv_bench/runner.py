SUITE_DATASET = {
    "tpch": "tpch",
    "tpch-nested": "tpch-nested",
    "tpcds": "tpcds",
    "dsb": "dsb@v1",
}  # default dataset per suite
ANSWER_DATASETS = {"tpch-dbgen"}  # datasets whose data reproduces the official TPC-H answers (base name; see paths)
LEGACY_ANSWER_VERSION = {"tpch-dbgen": "1.5.6"}  # unversioned `tpch-dbgen` was generated by DuckDB 1.5.6's dbgen


def machine_info() -> dict:
    cpu = "unknown"
    try:
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                cpu = line.split(":", 1)[1].strip()
                break
    except OSError:
        cpu = platform.processor()
    gov = None
    with contextlib.suppress(OSError):
        gov = Path("/sys/devices/system/cpu/cpu0/cpufreq/scaling_governor").read_text().strip()
    return {
        "cpu_model": cpu,
        "cores_logical": os.cpu_count(),
        "cores_physical": psutil.cpu_count(logical=False),
        "ram_bytes": psutil.virtual_memory().total,
        "ram_available_bytes_at_start": psutil.virtual_memory().available,
        "os": f"{platform.system()} {platform.release()}",
        "python": platform.python_version(),
        "cpu_governor": gov,
        "hostname": platform.node(),
    }


def engine_record(eng: Engine, engine_name: str) -> dict:
    """The ``engine`` block of the run metadata. ``allocator`` is recorded when the engine reports one."""
    build = eng.build_info()
    rec = {"name": engine_name, "version": eng.version(), "config": eng.config(), "build": build}
    if "allocator" in build:
        rec["allocator"] = build["allocator"]
    return rec


def git_info() -> dict:
    """Harness == engine repo here. `dirty` covers the whole repo (tracked changes and untracked files)."""

    def g(*a):
        return subprocess.run(["git", "-C", str(bench_root()), *a], capture_output=True, text=True).stdout.strip()

    porcelain = g("status", "--porcelain")
    return {
        "commit": g("rev-parse", "HEAD") or None,
        "branch": g("rev-parse", "--abbrev-ref", "HEAD") or None,
        "dirty": bool(porcelain),
        "dirty_files": len(porcelain.splitlines()),
    }


def dataset_provenance(ds_name: str, sf: float) -> dict:
    man = data_root() / "manifests" / f"{manifest_stem(ds_name, sf)}.sha256"
    prov = {
        "manifest_path": str(man),
        "manifest_sha256": hashlib.sha256(man.read_bytes()).hexdigest() if man.exists() else None,
    }
    base, version = split_dataset(ds_name)
    if base == "tpch-nested":
        prov["generator"] = (
            "krishiv_bench.nested_tpch (DuckDB) over the flat tpch dataset; layout of Comet's benchmarks/nested"
        )
    elif base == "tpch":
        r = subprocess.run(["tpchgen-cli", "--version"], capture_output=True, text=True)
        prov["generator"] = r.stdout.strip() or "tpchgen-cli (unknown version)"
    else:
        import duckdb

        if base in LEGACY_ANSWER_VERSION:
            gen_version = version or LEGACY_ANSWER_VERSION[base]
        else:
            gen_version = version or duckdb.__version__
        prov["generator"] = f"duckdb {gen_version} " + (
            "tpch extension (dbgen)" if base == "tpch-dbgen" else "tpcds extension (dsdgen)"
        )
    return prov


def load_queries(
    suite: str, engine: str, only: list[str] | None = None, dataset_root: Path | None = None
) -> list[Query]:
    """bench/queries/<suite>/qNN.sql; an engine-specific override lives in bench/queries/<suite>/<engine>/qNN.sql.

    ClickBench (CC BY-NC-SA) is not stored here: its queries are fetched from a pinned upstream commit.
    """
    reason = unsupported_reason(engine, suite)
    if reason:
        raise SystemExit(reason)
    if suite in ("h2o-groupby", "h2o-join"):  # authored here; the checksum query rides on each Query
        from . import h2o

        return h2o.load_queries(suite, engine, only)
    if suite == "dsb":  # TPC-licensed templates: instantiated at dataset generation, stored with the dataset
        from . import dsb

        if dataset_root is None:
            raise SystemExit("the dsb suite needs its dataset directory (--sf N, generated by `krishiv-datasets dsb`)")
        return dsb.load_queries(dataset_root, only)
    if suite == "clickbench":  # licensed CC BY-NC-SA: fetched from a pinned upstream commit, never stored here
        texts = clickbench_queries.load(engine)
        return [Query(q, sql, suite) for q, sql in texts.items() if not only or q in only]
    d = queries_dir(suite)
    out = []
    for f in sorted(d.glob("q*.sql")):
        if only and f.stem not in only:
            continue
        ov = d / engine / f.name
        if ov.exists():
            out.append(Query(f.stem, ov.read_text(), suite))
            continue
        sql = f.read_text()
        if engine in clickbench_queries.SPARK_DIALECT:
            sql = backtick_identifiers(sql)
        out.append(Query(f.stem, sql, suite))
    return out


def backtick_identifiers(sql: str) -> str:
    """``sql`` with each double-quoted identifier written as Spark quotes one.

    The TPC-DS texts come from DuckDB, where ``AS "order count"`` names a column. In Spark SQL a double-quoted
    token is a string literal (``spark.sql.ansi.doubleQuotedIdentifiers`` is off by default), so Spark 4.2 rejects
    those eight queries with ``PARSE_SYNTAX_ERROR``; its identifier quote is the backtick. Single-quoted string
    literals (``''`` escapes a quote) are left as they are; a doubled ``""`` inside a name is one ``"`` and a
    backtick inside a name is doubled.
    """
    out: list[str] = []
    i, n = 0, len(sql)
    while i < n:
        c = sql[i]
        if c == "'":  # a string literal, to its closing quote ('' is an escaped quote)
            j = i + 1
            while j < n:
                if sql[j] == "'" and j + 1 < n and sql[j + 1] == "'":
                    j += 2
                elif sql[j] == "'":
                    break
                else:
                    j += 1
            out.append(sql[i : j + 1])
            i = j + 1
        elif c == '"':
            j = i + 1
            while j < n:  # to the closing quote ("" is an escaped quote)
                if sql[j] == '"' and j + 1 < n and sql[j + 1] == '"':
                    j += 2
                elif sql[j] == '"':
                    break
                else:
                    j += 1
            if j >= n:  # unterminated: left for the engine to reject
                out.append(sql[i:])
                break
            name = sql[i + 1 : j].replace('""', '"')
            out.append("`" + name.replace("`", "``") + "`")
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def cold_record(cold: bool) -> dict:
    """The ``cold`` block of the run metadata: results of a cold run are not comparable with warm ones."""
    if not cold:
        return {"enabled": False}
    return {
        "enabled": True,
        "method": "posix_fadvise(POSIX_FADV_DONTNEED) on every dataset file before each run "
        "(run, h2o: warm-up included; reproduce, abba: each timed run)",
    }


def percentile(xs: list[float], p: float) -> float:
    """Nearest-rank percentile. With few iterations p99 == max (documented in the README)."""
    s = sorted(xs)
    k = max(0, min(len(s) - 1, int(-(-p / 100 * len(s) // 1)) - 1))
    return s[k]


def load_expected_rows(suite: str, sf: float) -> dict[str, int]:
    f = queries_dir(suite) / f"expected_rows_sf{fmt_sf(sf)}.json"
    return json.loads(f.read_text()) if f.exists() else {}


def order_fields(sql: str) -> dict:
    """What the cross-engine row comparison needs to know about the query's ordering (stored in the result JSON)."""
    ordered = compare.has_top_level_order_by(sql)
    limit, offset = compare.derive_limit(sql) if ordered else (None, False)
    return {
        "has_order_by": ordered,
        "sort_keys": compare.derive_sort_keys(sql) if ordered else None,
        "limit": limit,
        "has_offset": offset,
    }


def run_suite(
    engine_name: str,
    suite: str,
    sf: float,
    iterations: int = 5,
    warmup: int = 2,
    only: list[str] | None = None,
    engine_kwargs: dict | None = None,
    timeout_s: float | None = 600,
    dataset: str | None = None,
    cold: bool = False,
    min_mem_avail: float | None = memguard.DEFAULT_MIN_FRACTION,
    mem_retries: int = memguard.DEFAULT_RETRIES,
) -> Path:
    ds_name = dataset or SUITE_DATASET[suite]
    root = dataset_dir(ds_name, sf)
    tables = sorted(p.stem for p in root.glob("*.parquet"))
    if not tables:
        raise SystemExit(f"no dataset at {root}; run `uv run krishiv-datasets {ds_name} --sf {sf}`")
    eng: Engine = make_engine(engine_name, **(engine_kwargs or {}))
    expected = load_expected_rows(suite, sf)
    answers = {}
    oracle_rows: dict[str, list[tuple]] = {}  # dsb: DuckDB's typed answers
    base, version = split_dataset(ds_name)
    if suite == "tpch" and base in ANSWER_DATASETS:
        # Official answers come from the running DuckDB's tpch extension, which matches only its own dbgen output:
        # check only when the dataset's generator version is the running one.
        import duckdb

        generator = version or LEGACY_ANSWER_VERSION[base]
        if generator != duckdb.__version__:
            print(
                f"WARNING: {ds_name!r} was generated by DuckDB {generator}; "
                f"answers not checked with {duckdb.__version__}"
            )
        else:
            try:
                answers = compare.load_tpch_answers(sf)
            except Exception as e:  # e.g. extension not installable offline
                print(f"WARNING: official answers unavailable: {e}")
    ds = Dataset(ds_name, sf, root, tables)
    queries = load_queries(suite, engine_name, only, root)
    if suite == "dsb":
        from . import dsb

        oracle_rows = dsb.load_oracle(root)

    mem_floor = memguard.threshold_bytes(min_mem_avail) if min_mem_avail else None
    started = dt.datetime.now(dt.UTC)
    sf_s = fmt_sf(sf)
    stem = f"{started.strftime('%Y%m%dT%H%M%SZ')}_{engine_name}_{ds_name}_sf{sf_s}"
    record = {
        "schema": 2,
        "started_utc": started.isoformat(),
        "machine": machine_info(),
        "git": {"repo": "krishiv-engine (harness lives in bench/)", **git_info()},
        "engine": engine_record(eng, engine_name),
        "dataset": {
            "name": ds_name,
            "scale_factor": sf,
            "path": str(root),
            "tables": tables,
            **dataset_provenance(ds_name, sf),
        },
        "suite": suite,
        "iterations": iterations,
        "warmup": warmup,
        "timeout_s": timeout_s,
        "cold": cold_record(cold),
        "mem_guard": {"min_mem_avail_fraction": min_mem_avail, "threshold_bytes": mem_floor, "retries": mem_retries},
        "answers_available": bool(answers or oracle_rows),
        "queries": {},
    }
    rows_store: dict[str, list] = {}
    MAX_STORED_ROWS = 1_000_000
    eng.setup(ds)
    pool = cf.ThreadPoolExecutor(max_workers=1)
    try:
        for q in queries:
            entry: dict = {"iterations": iterations}
            times, meas = [], []
            invalid: list[dict] = []
            rows: list[tuple] = []
            try:
                for i in range(warmup + iterations):
                    for attempt in range(mem_retries + 1):
                        if mem_floor:
                            reached, _ = memguard.wait_for_memory(mem_floor)
                            if not reached:
                                raise MemoryError(f"MemAvailable stayed below {mem_floor} bytes; host memory not free")
                        if cold:
                            evict_page_cache(root)
                        # No sampler when the guard is off: opting out restores uninstrumented runs
                        # (its /proc reads would show in in-process adapters' rchar/syscr).
                        sampler = memguard.MemSampler() if mem_floor else None
                        eng.begin_measure()
                        m = None
                        failure: Exception | None = None
                        try:
                            with sampler if sampler is not None else contextlib.nullcontext():
                                t0 = time.perf_counter()
                                fut = pool.submit(eng.run, q)
                                try:
                                    rows = fut.result(timeout=timeout_s)
                                except cf.TimeoutError:
                                    eng.cancel()
                                    with contextlib.suppress(Exception):
                                        fut.result(timeout=30)
                                    pool.shutdown(wait=False, cancel_futures=True)
                                    pool = cf.ThreadPoolExecutor(max_workers=1)
                                    raise TimeoutError(f"query exceeded {timeout_s}s") from None
                                dtm = time.perf_counter() - t0
                        except Exception as e:
                            failure = e  # decided below: memory reclaimed (retry) or a real failure
                        finally:
                            m = eng.end_measure()
                        low = sampler.min_available if sampler is not None else None
                        if mem_floor and low is not None and memguard.is_invalid(low, mem_floor):
                            invalid.append(memguard.InvalidSample(i, attempt, low, mem_floor).as_dict())
                            continue
                        if failure is not None:
                            raise failure
                        if i >= warmup:
                            times.append(dtm)
                            meas.append(m)
                        break
                    else:
                        # Warm-up too: timings must not follow a warm-up done under memory pressure.
                        raise MemoryError(f"{memguard.INVALID_REASON} in all {mem_retries + 1} attempts of run {i}")
            except Exception as e:  # record, keep going
                entry.update(error_fields(e))
                if invalid:
                    entry["invalid_samples"] = invalid
                record["queries"][q.id] = entry
                print(f"  {q.id}: ERROR {entry['error'][:120]}")
                continue
            ordered = compare.has_top_level_order_by(q.sql)
            entry.update(
                order_fields(q.sql),
                times_s=times,
                p50_s=statistics.median(times),
                p99_s=percentile(times, 99),
                min_s=min(times),
                max_s=max(times),
                mean_s=statistics.fmean(times),
                throughput_qps=len(times) / sum(times),
                rows_returned=len(rows),
                expected_rows=expected.get(q.id),
                rows_match_expected=(len(rows) == expected[q.id]) if q.id in expected else None,
                **resource_fields(meas, times),
            )
            if invalid:
                entry["invalid_samples"] = invalid
            if q.id in oracle_rows:
                ok, msg = compare.rows_match(rows, oracle_rows[q.id], ordered, sql=q.sql)
                entry["answer_check"] = {"status": "pass" if ok else "fail", "detail": msg}
            elif q.id in answers:
                ok, msg = compare.answer_check(rows, answers[q.id], ordered)
                entry["answer_check"] = {"status": "pass" if ok else "fail", "detail": msg}
            else:
                entry["answer_check"] = {
                    "status": "not_checked",
                    "detail": f"dataset {ds_name!r} does not reproduce the official answers (use tpch-dbgen)"
                    if suite == "tpch"
                    else "no oracle answer for this query"
                    if suite == "dsb"
                    else "no official answer set",
                }
            if len(rows) <= MAX_STORED_ROWS:
                rows_store[q.id] = rows
                entry["rows_stored"] = True
            else:
                entry["rows_stored"] = False
            ac = entry["answer_check"]
            flag = "" if ac["status"] != "fail" else f"  ANSWER MISMATCH: {ac['detail'][:100]}"
            print(f"  {q.id}: p50={entry['p50_s'] * 1000:8.1f} ms rows={len(rows)} answer={ac['status']}{flag}")
            record["queries"][q.id] = entry
    finally:
        pool.shutdown(wait=False, cancel_futures=True)
        eng.teardown()
    record["finished_utc"] = dt.datetime.now(dt.UTC).isoformat()
    out = results_dir()
    out.mkdir(parents=True, exist_ok=True)
    compare.save_rows(out / f"{stem}.rows.json.gz", rows_store)
    record["rows_file"] = f"{stem}.rows.json.gz"
    f = out / f"{stem}.json"
    f.write_text(json.dumps(record, indent=2))
    return f
